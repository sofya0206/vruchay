#!/usr/bin/env bash
# Все действия в рабочих процессах должны быть закреплены по хешу коммита.
#
# Тег вроде v4 можно передвинуть на другой коммит — это может сделать владелец
# действия или тот, кто получил доступ к его репозиторию. Тогда в нашу сборку,
# где лежат ключи развёртывания и доступ к реестру образов, попадёт чужой код.
# Хеш коммита передвинуть нельзя.
#
# Обновление: посмотреть новый хеш тега и заменить, оставив тег комментарием:
#   curl -s https://api.github.com/repos/<владелец>/<действие>/commits/<тег> | jq -r .sha
set -euo pipefail

unpinned=$(grep -rhoE '^[[:space:]]*(-[[:space:]]+)?uses:[[:space:]]*[^[:space:]]+' \
  .github/workflows/ | grep -vE '@[0-9a-f]{40}' || true)

if [ -n "$unpinned" ]; then
  echo "Действия без закрепления по хешу:"
  echo "$unpinned"
  echo
  echo "Замените тег на хеш коммита, тег оставьте комментарием рядом."
  exit 1
fi

echo "Все действия закреплены по хешу."
