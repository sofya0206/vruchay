import type { ReactNode } from 'react';

/**
 * Ссылка «Обсудить условия» из кабинета.
 *
 * Когда проба заканчивается, человеку нужно не сообщение «лимит исчерпан»,
 * а способ продолжить. Цен у нас нет, страницы с кнопкой «купить» — тоже:
 * единственный путь дальше — разговор, и вести к нему надо оттуда, где
 * человек упёрся, а не из раздела «Оплата», куда он не пойдёт.
 *
 * Открывается в новой вкладке намеренно: в этот момент в кабинете обычно
 * лежит загруженный список и наполовину собранный макет, и уводить с них
 * страницу — значит просить проделать работу заново.
 *
 * Ведёт на отдельную страницу, а не на якорь главной. Якорь `/#obsudit`
 * работал только для невошедшего посетителя: у вошедшего по адресу `/`
 * стоит «Обзор», и ссылка открывала ему его же дашборд — то есть форму
 * из кабинета нельзя было открыть вообще ни разу.
 */
export function DiscussTermsLink({ children = 'обсудить условия' }: { children?: ReactNode }) {
  return (
    <a
      href="/obsudit"
      target="_blank"
      rel="noreferrer"
      className="underline underline-offset-2"
    >
      {children}
    </a>
  );
}
