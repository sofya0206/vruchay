import { describe, expect, it } from 'vitest';
import { formatWhen, jobLook, plural, protocolTitle } from './format';

/*
 * Всё здесь считается от московского дня, а не от часового пояса машины:
 * иначе проверка проходила бы в Москве и падала в Калининграде.
 */

describe('когда это было', () => {
  const now = new Date('2026-08-28T09:00:00Z'); // 28 августа, полдень по Москве

  it('сегодняшнее называет сегодняшним', () => {
    expect(formatWhen('2026-08-28T05:00:00Z', now)).toBe('сегодня');
  });

  it('поздний вечер по Москве — всё ещё тот же день', () => {
    // 28 августа 23:30 по Москве = 20:30 UTC. По UTC это ещё 28-е,
    // но проверка нужна на обратном случае — см. следующий пример.
    expect(formatWhen('2026-08-28T20:30:00Z', now)).toBe('сегодня');
  });

  it('после полуночи по Москве наступает новый день, хотя по UTC ещё вчера', () => {
    // 28 августа 00:30 по Москве = 27 августа 21:30 UTC.
    expect(formatWhen('2026-08-27T21:30:00Z', now)).toBe('сегодня');
  });

  it('вчерашнее называет вчерашним', () => {
    expect(formatWhen('2026-08-27T09:00:00Z', now)).toBe('вчера');
  });

  it('давнее показывает датой без года', () => {
    expect(formatWhen('2026-06-17T09:00:00Z', now)).toBe('17 июня');
  });

  it('прошлогоднее показывает с годом', () => {
    expect(formatWhen('2025-06-17T09:00:00Z', now)).toContain('2025');
  });

  it('на испорченной дате молчит, а не пишет Invalid Date', () => {
    expect(formatWhen('не дата', now)).toBe('');
  });
});

describe('состояние задания', () => {
  it('выпуск с ошибками не выдаёт за полностью удачный', () => {
    expect(jobLook('done', 3).label).toBe('готово, часть с ошибками');
    expect(jobLook('done', 0)).toEqual({ label: 'готово', tone: 'done' });
  });

  it('называет остальные состояния по-человечески', () => {
    expect(jobLook('queued').label).toBe('в очереди');
    expect(jobLook('running').label).toBe('идёт выпуск');
    expect(jobLook('failed').label).toBe('не удалось');
    expect(jobLook('canceled').label).toBe('отменено');
  });
});

describe('название материала под протокол', () => {
  it('содержит московскую дату', () => {
    // 1 сентября 00:30 по Москве = 31 августа 21:30 UTC.
    expect(protocolTitle(new Date('2026-08-31T21:30:00Z'))).toBe('Мероприятие от 01.09.2026');
  });
});

describe('склонение по числу', () => {
  it('считает как по-русски', () => {
    const word = (n: number) => plural(n, 'документ', 'документа', 'документов');
    expect(word(1)).toBe('документ');
    expect(word(2)).toBe('документа');
    expect(word(5)).toBe('документов');
    expect(word(11)).toBe('документов');
    expect(word(21)).toBe('документ');
    expect(word(114)).toBe('документов');
  });
});
