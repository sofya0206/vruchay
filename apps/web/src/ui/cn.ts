import { twMerge } from 'tailwind-merge';

/**
 * Склейка классов Tailwind, в которой побеждает последний.
 *
 * Обычная склейка строкой этого не даёт: у Tailwind порядок классов
 * в атрибуте `class` ничего не решает — побеждает тот, что стоит позже
 * в собранном CSS. Поэтому базовый `w-full` компонента переспоривал
 * `w-44`, переданный снаружи, и поле всё равно растягивалось на всю
 * строку. Обходили это обёртками нужной ширины вокруг поля.
 *
 * `twMerge` знает, какие классы описывают одно и то же свойство, и
 * выбрасывает все, кроме последнего: базовый набор компонента остаётся
 * умолчанием, а не запретом.
 */
export function cn(...classes: (string | false | null | undefined)[]): string {
  return twMerge(classes.filter(Boolean).join(' '));
}
