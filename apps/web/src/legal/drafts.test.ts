import { describe, expect, it } from 'vitest';
import oferta from './oferta.md?raw';
import dpa from './dpa.md?raw';
import { DRAFT_MARK, splitDraft } from './fill';

/*
 * Черновики договоров опубликованы страницами приложения. Пометка о том,
 * что юрист их не смотрел, — единственное, что отличает рабочий текст
 * от действующего договора: без неё на черновик сошлются в сделке.
 * Поэтому она проверяется, а не держится на внимательности.
 */

const DRAFTS: [string, string][] = [
  ['оферта', oferta],
  ['договор-поручение', dpa],
];

/** Имена, которые подставляются при сборке из данных предпринимателя. */
const KNOWN = ['НАИМЕНОВАНИЕ', 'ИНН', 'ОГРНИП', 'АДРЕС', 'EMAIL', 'ТЕЛЕФОН', 'ДАТА_РЕДАКЦИИ'];

describe.each(DRAFTS)('черновик: %s', (_name, source) => {
  it('начинается с пометки о черновике', () => {
    expect(source.split('\n')[0].trim()).toBe(DRAFT_MARK);
  });

  it('пометка снимается разбором и в текст документа не попадает', () => {
    const { draft, body } = splitDraft(source);
    expect(draft).toBe(true);
    expect(body).not.toContain(DRAFT_MARK);
    expect(body.startsWith('>') || body.startsWith('#')).toBe(true);
  });

  it('не содержит заглушек, кроме подставляемых при сборке', () => {
    const found = [...source.matchAll(/\{\{([^}]+)\}\}/g)].map((m) => m[1].trim());
    expect([...new Set(found)].filter((name) => !KNOWN.includes(name))).toEqual([]);
  });

  it('называет реквизиты стороны', () => {
    expect(source).toMatch(/ИНН \{\{ИНН\}\}/);
    expect(source).toMatch(/ОГРНИП \{\{ОГРНИП\}\}/);
  });
});

describe('оферта', () => {
  it('квалифицирована как лицензионный договор, а не оказание услуг', () => {
    // От квалификации зависят льгота по НДС (пп. 26 п. 2 ст. 149 НК РФ)
    // и возможность заявиться в реестр российского ПО. Переписать документ
    // как «услуги по изготовлению грамот» — значит потерять оба основания.
    expect(oferta).toMatch(/простую \(неисключительную\) лицензию/);
    expect(oferta).toMatch(/статьи 1235, 1286 ГК РФ|статей 1235, 1286 ГК РФ/);
    expect(oferta).toMatch(/не оказывает\s*\n?\s*услуг/);
    expect(oferta).toMatch(/подпункт 26 пункта 2 статьи 149 НК РФ/);
  });
});

describe('договор-поручение', () => {
  it('содержит обязательные условия части 3 статьи 6 152-ФЗ', () => {
    // Перечень данных, перечень действий, цели, конфиденциальность,
    // требования локализации и статьи 18.1, обязанность подтвердить меры.
    expect(dpa).toMatch(/## 2\. Перечень персональных данных/);
    expect(dpa).toMatch(/## 3\. Перечень действий и цели обработки/);
    expect(dpa).toMatch(/соблюдать конфиденциальность/);
    expect(dpa).toMatch(/часть 5 статьи 18 152-ФЗ/);
    expect(dpa).toMatch(/статьями 18\.1 и 19 152-ФЗ/);
    expect(dpa).toMatch(/Трансграничная передача персональных данных не осуществляется/);
  });

  it('распределяет роли: оператор — заказчик, обработчик — сервис', () => {
    expect(dpa).toMatch(/Обработчик не обязан получать согласие субъекта/);
    expect(dpa).toMatch(
      /Ответственность перед субъектом персональных данных за действия\s*\n?\s*Обработчика несёт Оператор/,
    );
  });
});
