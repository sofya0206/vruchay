import { describe, expect, it } from 'vitest';
import source from './privacy.md?raw';

/*
 * Политика — юридический документ, опубликованный по постоянному адресу.
 * Недописанный текст на нём хуже отсутствующего: он выглядит готовым.
 * Эти проверки ловят ровно то, что однажды уже просочилось.
 */

/** Имена, которые подставляются при сборке из данных предпринимателя. */
const KNOWN = [
  'НАИМЕНОВАНИЕ',
  'ИНН',
  'ОГРНИП',
  'АДРЕС',
  'EMAIL',
  'ТЕЛЕФОН',
  'ДАТА_РЕДАКЦИИ',
];

describe('текст политики обработки данных', () => {
  it('не содержит заглушек, кроме подставляемых при сборке', () => {
    const found = [...source.matchAll(/\{\{([^}]+)\}\}/g)].map((m) => m[1].trim());
    const unknown = [...new Set(found)].filter((name) => !KNOWN.includes(name));

    // Заглушки вида «{{СРОК: 6 часов}}» подстановкой не заменяются и выводятся
    // на страницу как есть. Проверка на странице их тоже не видела — потому
    // они и дожили до боевой публикации.
    expect(unknown).toEqual([]);
  });

  it('не содержит пометок о незавершённости', () => {
    const markers = ['БОЛВАНКА', 'TODO', 'FIXME', 'требует проверки юристом', 'заполнить'];
    const hit = markers.filter((m) => source.toLowerCase().includes(m.toLowerCase()));
    expect(hit).toEqual([]);
  });

  it('называет оператора, срок хранения и права субъекта', () => {
    // Минимальный состав по ч. 1 ст. 18.1 и ст. 14 152-ФЗ: без любого из этих
    // разделов документ не выполняет свою задачу.
    expect(source).toMatch(/ИНН \{\{ИНН\}\}/);
    expect(source).toMatch(/Сроки хранения/);
    expect(source).toMatch(/Права субъекта персональных данных/);
    expect(source).toMatch(/отозвать согласие/);
  });

  it('прямо утверждает, что трансграничной передачи нет', () => {
    // Это главное отличие от сервиса, от которого мы уходим, и главный
    // ответ в уведомлении Роскомнадзора — формулировка должна быть в тексте.
    expect(source).toMatch(/Трансграничная передача персональных данных не осуществляется/);
  });

  it('указывает, что данные хранятся в России', () => {
    expect(source).toMatch(/на территории Российской Федерации/);
  });
});
