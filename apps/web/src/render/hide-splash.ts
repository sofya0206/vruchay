/**
 * Убирает заставку из разметки, когда приложение отрисовалось.
 *
 * Живёт отдельно от точки входа по одной причине: её поведение однажды
 * оказалось неверным и никем не проверялось. Заставку убирали плавно
 * и полагались на событие `transitionend`, а оно не наступало вовсе —
 * см. ниже. Заставка доживала до страховочного таймера, и эти
 * шестьсот миллисекунд печатались в готовых грамотах.
 *
 * На странице печати заставки нет вовсе: её снимает разметка, ещё
 * до запуска приложения (см. `apps/web/index.html`). Здесь остаётся
 * только кабинет, где заставка полезна.
 */
export function hideSplash(doc: Document = document): void {
  const splash = doc.getElementById('splash');
  if (!splash) return;

  /*
   * Сначала снимаем анимацию появления, и только потом трогаем прозрачность.
   *
   * Анимация объявлена с `forwards`: она удерживает `opacity` и после
   * своего конца, а инлайновый стиль такую заливку не перебивает.
   * Отсюда и брался тот отказ: значение не менялось, переход не начинался,
   * `transitionend` не наступал никогда.
   */
  splash.style.animation = 'none';
  // Принудительный пересчёт стилей между снятием анимации и новым
  // значением прозрачности: без него браузер увидит обе правки разом
  // и покажет рывок вместо перехода.
  splash.getBoundingClientRect();

  splash.style.transition = 'opacity 0.25s ease-out';
  splash.style.opacity = '0';
  splash.addEventListener('transitionend', () => splash.remove(), { once: true });

  // Страховка остаётся: во вкладке в фоне браузер переходы не проигрывает,
  // и события можно не дождаться. Но теперь это именно страховка,
  // а не единственный работающий путь.
  setTimeout(() => splash.remove(), 600);
}
