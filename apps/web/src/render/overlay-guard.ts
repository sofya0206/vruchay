/**
 * Страховка страницы печати: на листе нет ничего поверх макета.
 *
 * Сделана по образцу проверки шрифтов, которая живёт рядом в RenderPage
 * и однажды уже спасла пачку документов, напечатанных запасным шрифтом.
 * Смысл тот же: печатать бракованный документ хуже, чем не печатать
 * вовсе. Не напечатанная строка попадает в отчёт «кого выпуск не осилил»,
 * и человек об этом узнаёт; напечатанный поверх фамилии зелёный квадрат
 * узнаёт уже награждённый.
 *
 * Повод — блокер 28.08.2026: заставка приложения (`#splash` из index.html)
 * непрозрачным слоем закрывала лист. Сама заставка теперь снимается
 * разметкой до запуска приложения, но проверка нужна не от неё одной:
 * поверх листа может оказаться что угодно — баннер обновления, всплывающее
 * окно расширения, будущая шапка кабинета, случайно попавшая на маршрут
 * печати.
 *
 * Проверка намеренно не знает про DOM больше, чем ей нужно: так её
 * можно проверить тестами, не поднимая браузер.
 */

/** Узел страницы в том объёме, который нужен проверке. */
export interface ProbeNode {
  closest(selector: string): unknown;
}

/** Документ в том объёме, который нужен проверке. */
export interface ProbeDocument {
  getElementById(id: string): unknown;
  elementsFromPoint(x: number, y: number): ProbeNode[];
}

/** Признак листа документа в разметке страницы печати. */
export const SHEET_SELECTOR = '[data-sheet]';

export interface Rect {
  left: number;
  top: number;
  width: number;
  height: number;
}

export interface Viewport {
  width: number;
  height: number;
}

/**
 * Точки, в которых спрашиваем «кто здесь сверху».
 *
 * Пять: середина и четыре угла с отступом внутрь. Одной середины мало —
 * слой может закрывать только часть листа (рамка, полоса сверху, уголок
 * с водяным знаком). Больше пяти не нужно: слой, не задевший ни одной
 * из них, занимает меньше сотой доли листа и в наградном документе
 * незаметен так же, как пылинка на бумаге.
 *
 * Отступ внутрь на два пикселя — от округления: ровно на границе листа
 * браузер вправе вернуть и лист, и то, что за ним.
 */
export function probePoints(rect: Rect, viewport: Viewport): [number, number][] {
  const inset = 2;
  const left = rect.left + inset;
  const top = rect.top + inset;
  const right = rect.left + rect.width - inset;
  const bottom = rect.top + rect.height - inset;

  const points: [number, number][] = [
    [(rect.left + rect.width / 2), (rect.top + rect.height / 2)],
    [left, top],
    [right, top],
    [left, bottom],
    [right, bottom],
  ];

  // За пределами окна браузер вернёт пустой список: это не «лист закрыт»,
  // а «мы спросили не там». Лист бывает выше окна — например, документ
  // из нескольких листов подряд.
  return points.filter(
    ([x, y]) => x >= 0 && y >= 0 && x < viewport.width && y < viewport.height,
  );
}

/**
 * Что не так со страницей печати. `null` — всё в порядке, можно печатать.
 *
 * Возвращается не «да/нет», а строка: она уходит в `window.__RENDER_ERROR__`
 * и оттуда в отчёт о выпуске, где на неё смотрит человек.
 */
export function overlayProblem(
  doc: ProbeDocument,
  points: readonly (readonly [number, number])[],
): string | null {
  // Отдельным словом, а не общей формулировкой: это самая частая беда
  // и единственная, про которую сразу понятно, что делать.
  if (doc.getElementById('splash')) {
    return 'на странице печати осталась заставка приложения';
  }

  if (points.length === 0) {
    return 'лист документа не найден на странице';
  }

  for (const [x, y] of points) {
    const top = doc.elementsFromPoint(x, y)[0];
    if (!top) return 'лист документа не отрисован';
    if (!top.closest(SHEET_SELECTOR)) return 'поверх листа оказался посторонний слой';
  }

  return null;
}
