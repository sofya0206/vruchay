export interface Section {
  path: string;
  label: string;
  icon: LucideIcon;
  /** Короткая подпись для заглушки раздела, который ещё делается. */
  about: string;
}

/*
 * Разделы кабинета — единственный список, из которого рисуется навигация.
 *
 * Порядок повторяет ход работы: посмотреть, что происходит → собрать
 * материал → разослать → найти выданное → подключить к своему сайту →
 * заплатить. Настроек здесь нет намеренно: их открывают редко и из шапки,
 * а не по дороге к награждению.
 *
 * ───── ВЕТКАМ БЛОКА 1 ─────
 * Новый раздел добавляется ОДНОЙ строкой в этот массив и одной строкой
 * маршрута в размеченном месте App.tsx. Больше ни в навигацию, ни
 * в оболочку лезть не нужно.
 */
export const SECTIONS: Section[] = [
  {
    path: '/',
    // «Главное», а не «Обзор»: обзор звучит как отчёт, который смотрят,
    // а раздел — рабочий стол, с которого начинают день. Название
    // предложила Соня на приёмке.
    label: 'Главное',
    icon: LayoutDashboard,
    about: 'Что происходит с награждениями прямо сейчас',
  },
  {
    path: '/documents',
    label: 'Документы',
    icon: FileText,
    about: 'Бланки, макеты и поля: из чего выпускаются документы',
  },
  {
    path: '/mailing',
    label: 'Рассылка',
    icon: Mail,
    about: 'Письма участникам: шаблон, отправка и судьба каждого письма',
  },
  {
    path: '/registry',
    label: 'Реестр',
    icon: ShieldCheck,
    about: 'Всё выданное: поиск по фамилии, проверка подлинности, отзыв',
  },
  {
    path: '/integrations',
    label: 'Интеграции',
    icon: Plug,
    about: 'Форма на сайте, Тильда и доступ по API',
  },
  {
    path: '/billing',
    label: 'Оплата',
    icon: CreditCard,
    about: 'Тариф, счета и закрывающие документы',
  },
];

/**
 * Какой раздел считать открытым.
 *
 * «Главное» — только точное совпадение: иначе оно подсвечивалось бы на каждой
 * странице кабинета. Остальные — по началу адреса, чтобы редактор
 * материала (`/documents/:id`) относился к «Документам», а не выглядел
 * страницей вне разделов.
 */
export function activeSection(pathname: string): string | null {
  if (pathname === '/') return '/';

  const match = SECTIONS.filter((s) => s.path !== '/')
    .filter((s) => pathname === s.path || pathname.startsWith(`${s.path}/`))
    // Самый длинный подходящий адрес: если однажды появятся вложенные
    // разделы, подсветится ближний, а не тот, что просто начинается так же.
    .sort((a, b) => b.path.length - a.path.length)[0];

  return match?.path ?? null;
}
