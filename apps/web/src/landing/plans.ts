/**
 * Что входит в работу с нами — и цена, если она вообще названа.
 *
 * Публичных цен у сервиса нет: объём и стоимость обсуждаются в разговоре.
 * Но страницу не придётся переписывать, когда пакеты станут публичными:
 * цена здесь — данные, а не строчка в разметке. Указан `priceRub` — на
 * странице появится число, оставлен `null` — «по договорённости».
 *
 * Пока предложение одно, и это карточка. Добавятся пакеты с ценами —
 * тот же компонент разложит их сеткой, ничего не меняя в разметке.
 */

export interface Plan {
  id: string;
  name: string;
  /** Одна строка про объём: по ней человек узнаёт свой случай. */
  volume: string;
  /** Цена в рублях за год. null — не публикуется, обсуждается лично. */
  priceRub: number | null;
  features: string[];
  highlight?: boolean;
}

export const PLANS: Plan[] = [
  {
    id: 'agreement',
    name: 'Работа с организацией',
    volume: 'Объём — ваш календарь награждений на год',
    priceRub: null,
    features: [
      'Редактор макетов и списки участников',
      'Импорт из Excel, CSV и протоколов соревнований',
      'Рассылка с вашего домена, а не с адреса сервиса',
      'Проверка подлинности по QR-коду',
      'Форма на вашем сайте, Тильда и доступ по API',
      'Правила награждения по занятым местам',
      'Договор, счёт и акт: продавец — российский ИП',
      'Сотрудники работают каждый под своим входом',
    ],
    highlight: true,
  },
];

/** Что печатать в месте цены. */
export function planPrice(plan: Plan): { value: string; period: string | null } {
  if (plan.priceRub === null) return { value: 'По договорённости', period: null };
  return { value: `${plan.priceRub.toLocaleString('ru-RU')} ₽`, period: 'в год' };
}

/**
 * Есть ли у нас вообще публичные цены.
 *
 * От этого зависит разметка для поисковиков: цена, объявленная в Offer,
 * обязана совпадать с видимой на странице. Расхождение поисковик считает
 * обманом и снимает расширенный сниппет целиком.
 */
export function hasPublicPrices(plans: readonly Plan[] = PLANS): boolean {
  return plans.some((p) => p.priceRub !== null);
}

/**
 * Раскладка карточек. Классы сетки перечислены целиком: Tailwind собирает
 * их, читая исходники, и склеенное в переменной имя класса до сборки
 * не доедет.
 */
export function planGridClass(count: number = PLANS.length): string {
  if (count <= 1) return 'max-w-2xl';
  if (count === 2) return 'lg:grid-cols-2';
  return 'lg:grid-cols-3';
}
