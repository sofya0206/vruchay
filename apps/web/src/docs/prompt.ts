/**
 * Промпт, который человек копирует и отдаёт своему ИИ-помощнику.
 *
 * Ради этого и написана вся документация под машинное чтение: человек
 * не изучает наш API, а передаёт помощнику три вещи — где лежит справочник,
 * куда ходить и чем представляться. Дальше помощник читает llms-full.txt
 * и делает работу сам.
 *
 * Первой строкой идёт адрес выжимки: если из промпта уцелеет одна строка,
 * пусть это будет она.
 */
export const SITE = 'https://vruchay.ru';

export function integrationPrompt(token = 'вставьте сюда токен из кабинета'): string {
  return [
    `Прочитай ${SITE}/llms-full.txt — это полная документация API сервиса «Вручай».`,
    'Он выпускает именные документы: из таблицы участников делает по одному PDF на человека.',
    '',
    `Базовый адрес: ${SITE}/api`,
    `Заголовок для всех запросов: Authorization: Bearer ${token}`,
    '',
    'Что нужно сделать:',
    '1. Возьми мою таблицу участников (приложу файлом).',
    '2. Заведи документ и загрузи в него получателей.',
    '3. Проверь данные и покажи мне, что вызвало сомнения.',
    '4. Запусти выпуск, дождись готовности и скачай архив.',
    '',
    'Перед первым запросом, меняющим данные, покажи мне план: какие эндпоинты',
    'вызовешь и с какими телами. Токен никуда, кроме vruchay.ru, не отправляй.',
  ].join('\n');
}
