import { describe, expect, it } from 'vitest';
import source from './EditorPage.tsx?raw';

/*
 * На странице редактирования — только редактирование.
 *
 * Приёмка задачи звучит буквально так: ни одного элемента про отправку
 * и про получателей. Проверяем это по самому исходнику страницы, а не
 * по нарисованному экрану, и вот почему: вкладка «Письмо» возвращается
 * не тем, что кто-то нарисует её заново, а тем, что кто-то допишет
 * сюда `import { EmailTemplateEditor }` ради «одной маленькой панели».
 * Такой тест ловит именно это движение и называет его по имени.
 *
 * Список переменных и превью на строке данных к получателям не относятся:
 * это имена колонок и один образец для холста, а не работа со списком.
 * Поэтому запрещаем не запрос `useRecipients`, а экраны и слова.
 */

/** Экраны, которые уехали на «Рассылку» и в «Реестр». */
const MOVED_SCREENS = [
  'RecipientsTable',
  'EmailTemplateEditor',
  'ValidationScreen',
  'RulesTab',
  'RegistryTable',
];

/** Слова, которых на странице макета быть не может. */
const MOVED_WORDS = [
  'Получатели',
  'Письмо',
  'Отправить',
  'Разослать',
  'Рассылка',
  'Реестр',
  'Проверка',
];

describe('страница редактирования', () => {
  it('не подключает ни одного экрана про списки, письма и выданное', () => {
    for (const screen of MOVED_SCREENS) {
      expect(source, `${screen} должен жить на «Рассылке», а не в редакторе`).not.toContain(screen);
    }
  });

  it('не показывает ни одной подписи про отправку и получателей', () => {
    for (const word of MOVED_WORDS) {
      expect(source, `слово «${word}» на странице макета лишнее`).not.toContain(`>${word}<`);
    }
  });

  /*
   * Кнопка «Готово → к рассылке» стала переключателем «Редактор — Таблица»
   * в общей рамке страницы: у материала две стороны, и ходят между ними
   * десятки раз за вечер, а не один раз в конце. Требование то же самое —
   * уводить отсюда ссылкой, а не встроенной панелью, — поэтому проверяем
   * не подпись кнопки, а что дорога к списку по-прежнему одна и ведёт
   * туда же, куда вела.
   */
  it('уводит к таблице ссылкой, а не встроенной панелью', () => {
    expect(source).toContain('Открыть таблицу');
    expect(source).toContain('workspacePath');
  });

  it('оставляет себе холст, свойства, вставку переменных и сохранение', () => {
    for (const kept of ['SheetRenderer', 'PropertiesPanel', 'InsertMenu', 'Сохранено']) {
      expect(source, `${kept} — это и есть редактирование`).toContain(kept);
    }
  });
});
