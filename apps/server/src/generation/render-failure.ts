/**
 * Причина, по которой документ не создался, — словами.
 *
 * До этого в отчёт всегда уходила одна строка: «Документ не удалось
 * создать». Настоящая причина оставалась в журнале сервера, куда человек
 * не заглядывает и не должен. А решения у причин разные: не загрузился
 * шрифт — вернуть его в макет или выбрать другой; не отвечает хранилище —
 * подождать и продолжить; упал браузер — продолжить, он поднимется сам;
 * кончилось место — звонить нам.
 *
 * Сделано по образцу разбора недоставки писем (`mailing/bounce-reason.ts`):
 * там этот подход уже отработан, и заводить второй незачем.
 *
 * Технический текст не выбрасываем, а оставляем в журнале сервера:
 * поддержке он нужен, а в отчёте о награждении ему не место.
 */

interface Rule {
  reason: string;
  /**
   * Беда общая, а не в этой строке.
   *
   * Разница не умозрительная: одна плохая строка — это отчёт с именем
   * и продолжение выпуска, а недоступное хранилище — это триста
   * одинаковых строк в отчёте и три сотни впустую отрисованных
   * документов. Во втором случае выпуск надо остановить и сказать,
   * что случилось.
   */
  common: boolean;
  match: RegExp;
}

/*
 * Порядок важен: правила проверяются сверху вниз, узкое должно стоять
 * раньше общего. «Target closed» бывает и от нашей же остановки браузера,
 * поэтому падение браузера ищем раньше, чем общий отказ страницы.
 */
const RULES: Rule[] = [
  {
    reason: 'На сервере кончилось место',
    common: true,
    match: /enospc|no space left|edquot|disk\s*full|quotaexceeded/i,
  },
  {
    // «печатать нечем» — своё сообщение из PdfRenderer, когда браузер
    // не поднимается подряд. Остальное — как об этом говорит Playwright.
    reason: 'Браузер, который печатает документы, не удалось запустить',
    common: true,
    match: /печатать нечем|failed to launch|browsertype\.launch|executable doesn'?t exist/i,
  },
  {
    reason: 'Браузер, который печатает документы, аварийно завершился',
    common: true,
    match: /target .*closed|browser.*(?:closed|disconnected|crashed)|crash|protocol error|session closed|websocket/i,
  },
  {
    reason: 'Не загрузились шрифты макета',
    // Шрифт один на весь макет, но подмножество зависит от текста строки:
    // редкая буква в одной фамилии может не приехать там, где остальные
    // сто документов вышли исправными. Поэтому не общая беда — но если
    // подряд падают все, выпуск остановит счётчик неудач.
    common: false,
    match: /не загрузились шрифты|font/i,
  },
  {
    reason: 'Хранилище файлов не отвечает',
    common: true,
    match:
      /хранилищ|storage|s3|nosuchbucket|accessdenied|slowdown|requesttimeout|econnrefused|econnreset|enotfound|etimedout|getaddrinfo/i,
  },
  {
    reason: 'Страница документа не успела отрисоваться',
    // Обычно это тяжёлый фон или медленная сеть на одном документе.
    common: false,
    match: /timeout|timed out|exceeded|net::err_/i,
  },
  {
    reason: 'База данных не отвечает',
    common: true,
    match: /база|prisma|p1\d{3}|connection pool|deadlock/i,
  },
];

export interface RenderProblem {
  /** Что показать человеку в отчёте о выпуске. */
  reason: string;
  /** Беда общая: продолжать пакет бессмысленно. */
  common: boolean;
  /** Исходный текст — только для журнала сервера. */
  details: string;
}

/**
 * Разбирает исключение отрисовки в человеческую причину.
 *
 * Неизвестную причину не выдумываем: честнее сказать «документ создать
 * не удалось» и оставить подробности поддержке, чем назвать наугад.
 * Общей такую беду не считаем — иначе одна незнакомая ошибка
 * останавливала бы всё награждение.
 */
export function renderProblem(err: unknown): RenderProblem {
  const details = err instanceof Error ? err.message : String(err);
  const rule = RULES.find((r) => r.match.test(details));
  return {
    reason: rule?.reason ?? 'Документ не удалось создать',
    common: rule?.common ?? false,
    details,
  };
}

/**
 * Сколько строк подряд должно упасть с незнакомой причиной, чтобы считать
 * беду общей.
 *
 * Пять, а не одна: единичные неудачи бывают и на исправном сервисе —
 * тяжёлый фон, моргнувшая сеть. И не пятьдесят: смысл счётчика в том,
 * чтобы человек узнал о беде раньше, чем сервис перемелет весь список.
 */
export const FAILURE_STREAK = 5;

/**
 * То же для причин, которые сами по себе говорят об общей беде.
 *
 * Две, а не одна: и хранилище, и браузер умеют моргнуть на одной строке,
 * и ронять из-за этого награждение на тысячу человек не за что —
 * такую строку сервис повторит сам. Но если не отвечает и вторая подряд,
 * дело уже не в строке.
 */
export const COMMON_FAILURE_STREAK = 2;

/** Пора ли останавливать выпуск: беда общая, а не в этой строке. */
export function shouldStop(problem: RenderProblem, streak: number): boolean {
  return streak >= (problem.common ? COMMON_FAILURE_STREAK : FAILURE_STREAK);
}

/** Что написать в задании, когда выпуск остановлен из-за общей беды. */
export function jobStopMessage(reason: string): string {
  return (
    `Выпуск остановлен: ${reason.toLowerCase()}. ` +
    'Созданные документы сохранены, за остальные ничего не списано — ' +
    'когда причина устранится, выпуск можно продолжить с того же места.'
  );
}
