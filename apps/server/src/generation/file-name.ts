import { z } from 'zod';

/**
 * Имена файлов в архиве.
 *
 * Имя видит не разработчик, а секретарь, который распечатывает пачку грамот
 * и раскладывает их по конвертам. Поэтому по умолчанию это имя получателя,
 * а не идентификатор, — но одного умолчания мало: в одной организации файлы
 * складывают по номеру приказа, в другой по группе, и переименовывать
 * триста штук руками никто не станет.
 */

/** Что получится, если шаблон не задавали. */
export const DEFAULT_NAME_TEMPLATE = '%name';

/** Из чего собирается имя, кроме колонок таблицы. */
export interface NameContext {
  /** Порядковый номер в архиве, начиная с единицы. */
  number: number;
  /** Проверочный код документа — он же в QR-коде. */
  publicId?: string;
  ext: string;
}

const MAX_NAME_LENGTH = 80;

/*
 * Разделители пути и управляющие символы вырезаются дважды: и из шаблона
 * при проверке, и из готового имени.
 *
 * Дублирование намеренное. Шаблон приходит от пользователя, но подставляются
 * в него данные получателей, а они приходят из загруженного файла Excel —
 * туда «../../» попадёт не злым умыслом, так копипастой. Имя файла в архиве
 * с таким содержимым — это запись мимо каталога распаковки (zip slip),
 * поэтому чистим результат, а не только то, что человек набрал руками.
 */
/* eslint-disable no-control-regex */
/** Проверка шаблона. Без флага g: с ним `test` помнит позицию и врёт через раз. */
const HAS_FORBIDDEN = /[\x00-\x1f\x7f\\/:*?"<>|]/;
/** Чистка готового имени: те же символы, но вырезаем все вхождения. */
const FORBIDDEN = /[\x00-\x1f\x7f\\/:*?"<>|]/g;
/* eslint-enable no-control-regex */

/**
 * Символы управления направлением письма.
 *
 * Ими имя файла показывается не тем, чем является: «отчёт-\u202Efdp.exe»
 * читается на экране как «отчёт-exe.pdf». Настоящее расширение при этом
 * остаётся исполняемым. В именах участников такие символы не нужны никому.
 */
const BIDI = /[\u061c\u200e\u200f\u202a-\u202e\u2066-\u2069]/g;

/**
 * Шаблон имени. Проверяем до подстановки: разделитель пути, набранный руками,
 * — это уже попытка разложить архив мимо каталога, и молча вычистить её
 * значит не сказать человеку, что его шаблон понят не так, как он написал.
 */
export const nameTemplateSchema = z
  .string()
  .trim()
  .min(1, 'Шаблон имени не может быть пустым')
  .max(120, 'Шаблон имени длиннее 120 символов')
  .refine((v) => !HAS_FORBIDDEN.test(v), {
    message: 'В шаблоне имени нельзя использовать символы \\ / : * ? " < > |',
  });

/**
 * Подставляет значения в шаблон и приводит результат к пригодному имени файла.
 *
 * Неизвестная переменная становится пустотой, а не остаётся текстом «%group»:
 * файл с именем «%group» в архиве выглядит поломкой сервиса, тогда как это
 * всего лишь опечатка в названии колонки.
 */
export function buildFileName(
  template: string,
  data: Record<string, string>,
  ctx: NameContext,
): string {
  const values: Record<string, string> = {
    ...data,
    number: String(ctx.number),
    publicId: ctx.publicId ?? '',
  };

  const substituted = template.replace(
    /%([A-Za-zА-Яа-яЁё0-9_]+)/g,
    (_, key: string) => values[key] ?? '',
  );

  const cleaned = substituted
    .replace(FORBIDDEN, ' ')
    // Управление направлением письма: этими символами имя «счёт-fdp.exe»
    // показывается как «счёт-exe.pdf». Расширение в архиве при этом
    // настоящее, а человек видит безобидное.
    .replace(BIDI, '')
    // «..» — выход на каталог выше. Разделителей после чистки уже нет,
    // и сам по себе он безвреден, но оставлять в имени обломки пути
    // незачем: их всё равно кто-нибудь однажды склеит обратно.
    .replace(/\.{2,}/g, '.')
    .replace(/\s+/g, ' ')
    // Имя, начинающееся с точки, в архиве прячется.
    .replace(/^[.\s]+|[.\s]+$/g, '');

  const safe = trimToLength(cleaned, MAX_NAME_LENGTH).replace(/[.\s]+$/, '');

  const ext = ctx.ext === 'jpg' ? 'jpg' : 'pdf';
  return `${avoidReserved(safe) || 'Документ'}.${ext}`;
}

/**
 * Обрезает по символам, а не по единицам UTF-16.
 *
 * `slice` рубит по единицам кода и разрывает суррогатную пару пополам.
 * Половина пары — это не символ, а битый UTF-8 в имени записи архива:
 * распаковщик показывает вопросительный знак, а иногда отказывается
 * доставать файл вовсе. Эмодзи в фамилии не бывает, зато бывает в названии
 * мероприятия, которое человек вписал в шаблон имени.
 */
function trimToLength(value: string, max: number): string {
  const points = Array.from(value);
  return points.length <= max ? value : points.slice(0, max).join('');
}

/**
 * Имена, которые Windows держит за устройства.
 *
 * `CON`, `PRN`, `NUL`, `COM1` и им подобные зарезервированы вместе с любым
 * расширением: «CON.pdf» не создаётся так же, как «CON». Участник с фамилией
 * Кон или колонкой «PRN» в таблице — не выдумка, а распакованный архив,
 * в котором молча не хватает одного документа.
 *
 * Дописываем подчёркивание, а не выбрасываем имя: «Документ.pdf» вместо
 * фамилии хуже, чем «CON_.pdf».
 */
const RESERVED = /^(con|prn|aux|nul|com[1-9]|lpt[1-9])$/i;

function avoidReserved(name: string): string {
  return RESERVED.test(name) ? `${name}_` : name;
}

/**
 * Имя, которого ещё нет в архиве.
 *
 * Тёзки среди участников — обычное дело, а два файла с одним именем
 * распаковщик либо перезапишет, либо откажется распаковывать вовсе.
 */
export function uniqueName(used: Set<string>, name: string): string {
  let candidate = name;
  let n = 2;
  while (used.has(candidate)) {
    const dot = name.lastIndexOf('.');
    const base = dot > 0 ? name.slice(0, dot) : name;
    const ext = dot > 0 ? name.slice(dot) : '';
    candidate = `${base} (${n++})${ext}`;
  }
  used.add(candidate);
  return candidate;
}
