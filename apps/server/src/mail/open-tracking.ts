/**
 * Отметка о прочтении письма.
 *
 * В письмо подставляется прозрачная картинка размером в одну точку;
 * почтовый клиент загружает её при открытии, и мы узнаём, что письмо
 * прочитано. Другого способа нет: SMTP сообщает только о доставке
 * до почтового сервера, а что было дальше — молчит.
 *
 * Что записываем и чего не записываем. Записываем только факт и время.
 * Адрес обращения и сведения о браузере не сохраняем: для ответа
 * организатору «участник получил грамоту» они не нужны, а собирать
 * персональные данные сверх необходимого прямо запрещает ч. 5 ст. 5
 * 152-ФЗ. Соблазн тут есть — почтовые сервисы так делают, — но у нас
 * весь смысл в том, чтобы этого не делать.
 *
 * Точность у метода известная и невысокая: Gmail и Mail.ru кэшируют
 * картинки на своей стороне, часть клиентов не грузит их вовсе. Поэтому
 * «прочитано» — это «точно прочитано», а его отсутствие ничего не значит.
 * Так и подписано в реестре.
 */

/**
 * Прозрачный GIF 1×1, 43 байта. Именно GIF, а не PNG: он меньше и его
 * понимают вообще все почтовые клиенты, включая совсем старые.
 */
export const PIXEL_GIF = Buffer.from(
  'R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7',
  'base64',
);

export const PIXEL_MIME = 'image/gif';

/** Путь картинки для письма. Идентификатор письма — uuid, его не подобрать. */
export function pixelUrl(publicUrl: string, emailId: string): string {
  return `${publicUrl.replace(/\/+$/, '')}/api/v1/t/o/${emailId}.gif`;
}

/**
 * Дописывает картинку в конец письма.
 *
 * Ставим последним элементом тела, чтобы при загрузке она не сдвигала
 * текст. Пустой alt и нулевые отступы — иначе некоторые клиенты рисуют
 * рамку или значок «изображение не загружено» прямо под подписью.
 */
export function withOpenPixel(html: string, publicUrl: string, emailId: string): string {
  const src = pixelUrl(publicUrl, emailId);
  return `${html}<img src="${src}" width="1" height="1" alt="" style="display:block;width:1px;height:1px;border:0;margin:0" />`;
}
