/**
 * Ограничение отправки с общего домена.
 *
 * Пока у организации нет своего домена, её письма уходят с нашего —
 * `noreply@vruchay.ru`. Значит, репутация этого адреса общая на всех:
 * один заказчик, разославший тысячу писем по купленной базе, испортит
 * доставляемость всем остальным, включая нас. Чинится такое месяцами
 * и не техникой, а перепиской с почтовыми провайдерами.
 *
 * Поэтому объём с общего домена ограничен. Со **своего** домена
 * ограничения нет: там репутация принадлежит самому заказчику, и он
 * отвечает за неё сам.
 *
 * Числа выбраны так, чтобы не мешать настоящей работе: обычное
 * награждение — это от десятков до пары сотен писем за раз, и такой
 * поток проходит свободно. Упереться в потолок можно только рассылкой,
 * на которую наградной сервис не рассчитан.
 */

export interface SharedDomainLimits {
  /** Сколько писем с общего домена организация может отправить за сутки. */
  perDay: number;
  /** И за один запуск рассылки. */
  perBatch: number;
}

export function sharedDomainLimits(): SharedDomainLimits {
  return {
    perDay: Number(process.env.SHARED_DOMAIN_DAILY_LIMIT ?? 500),
    perBatch: Number(process.env.SHARED_DOMAIN_BATCH_LIMIT ?? 300),
  };
}

export interface LimitCheck {
  /** Сколько писем уже ушло с общего домена за последние сутки. */
  sentToday: number;
  /** Сколько собираемся отправить сейчас. */
  adding: number;
}

/**
 * Что ответить, если объём превышен, — или null, если всё в порядке.
 *
 * Сообщение объясняет и причину, и выход. Просто «превышен лимит»
 * оставляет человека в тупике: он не сделал ничего дурного, а его
 * награждение встало.
 */
export function sharedDomainRefusal(
  { sentToday, adding }: LimitCheck,
  limits = sharedDomainLimits(),
): string | null {
  if (adding > limits.perBatch) {
    return (
      `За один раз с общего адреса уходит не больше ${limits.perBatch} писем, ` +
      `а отмечено ${adding}. Разбейте на несколько рассылок или подключите ` +
      `свой домен в настройках — со своего домена ограничения нет.`
    );
  }

  if (sentToday + adding > limits.perDay) {
    const left = Math.max(0, limits.perDay - sentToday);
    return (
      `За сутки с общего адреса уходит не больше ${limits.perDay} писем: ` +
      `сегодня уже отправлено ${sentToday}, осталось ${left}. ` +
      `Подключите свой домен в настройках — со своего домена ограничения нет, ` +
      `и письма вызывают больше доверия.`
    );
  }

  return null;
}
