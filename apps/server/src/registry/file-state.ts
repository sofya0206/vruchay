/**
 * Состояние выданного документа.
 *
 * Три состояния, а не флаг «отозван», потому что за отзывом и перевыпуском
 * стоят разные события и разные ответы человеку с бумагой в руках:
 *
 * - `valid` — документ действителен;
 * - `revoked` — организация признала его недействительным, замены нет;
 * - `replaced` — выдан новый вместо этого (опечатка в фамилии, неверный
 *   разряд), и предъявителю старого надо показать, где взять новый.
 *
 * Отдельного поля-состояния в базе нет намеренно: оно выводится из фактов —
 * снятой отметки проверки и найденного файла-замены. Поле пришлось бы
 * держать в согласии с этими фактами при каждом перевыпуске, отмене
 * и удалении, а расхождение означало бы, что реестр говорит одно,
 * а страница проверки — другое.
 */
export type FileState = 'valid' | 'revoked' | 'replaced';

export const FILE_STATES: readonly FileState[] = ['valid', 'revoked', 'replaced'];

/**
 * Что показать про этот файл.
 *
 * Отзыв сильнее замены: он — прямое заявление организации о том, что
 * документа больше нет. Перевыпуск такого заявления не делает, он лишь
 * переводит стрелку на новый документ.
 */
export function fileState(file: { verifyRevoked: boolean; replacedById: string | null }): FileState {
  if (file.verifyRevoked) return 'revoked';
  if (file.replacedById) return 'replaced';
  return 'valid';
}
