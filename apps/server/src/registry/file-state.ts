/**
 * Состояние выданного документа.
 *
 * Четыре состояния, а не флаг «отозван», потому что за отзывом,
 * перевыпуском и истечением срока стоят разные события и разные ответы
 * человеку с бумагой в руках:
 *
 * - `valid` — документ действителен;
 * - `revoked` — организация признала его недействительным, замены нет;
 * - `replaced` — выдан новый вместо этого (опечатка в фамилии, неверный
 *   разряд), и предъявителю старого надо показать, где взять новый;
 * - `expired` — срок действия вышел: документ был настоящим и остаётся
 *   настоящим, но подтверждает уже прошлое, а не настоящее.
 *
 * Отдельного поля-состояния в базе нет намеренно: оно выводится из фактов —
 * снятой отметки проверки, найденного файла-замены и даты окончания срока.
 * Поле пришлось бы держать в согласии с этими фактами при каждом
 * перевыпуске, отмене и удалении, а истечение срока — ещё и по часам,
 * ночной задачей; расхождение означало бы, что реестр говорит одно,
 * а страница проверки — другое.
 */
export type FileState = 'valid' | 'revoked' | 'replaced' | 'expired';

export const FILE_STATES: readonly FileState[] = ['valid', 'revoked', 'replaced', 'expired'];

/** Факты о файле, из которых выводится состояние. */
export interface FileStateFacts {
  verifyRevoked: boolean;
  replacedById: string | null;
  /** Когда срок действия кончается. Нет срока — документ бессрочный. */
  expiresAt?: Date | null;
}

/**
 * Что показать про этот файл.
 *
 * Порядок — по силе заявления организации. Отзыв сильнее всего: это
 * прямое заявление о том, что документа больше нет. Замена — стрелка
 * на новый документ, и она важнее срока: у заменённого документа срок
 * ни о чём не говорит, действует его замена. Срок — последнее, потому
 * что наступает сам, без чьего-либо решения.
 *
 * Граница срока: документ действителен до самого момента `expiresAt`
 * и перестаёт быть действительным с него. Ровно в этот момент — уже
 * истёк: «действителен до 17 июня» означает, что 17 июня он уже нет.
 */
export function fileState(file: FileStateFacts, now: Date = new Date()): FileState {
  if (file.verifyRevoked) return 'revoked';
  if (file.replacedById) return 'replaced';
  if (file.expiresAt && file.expiresAt.getTime() <= now.getTime()) return 'expired';
  return 'valid';
}
