import { describe, expect, it } from 'vitest';
import { cell } from './registry.service';

/*
 * Ячейка выгрузки — единственное место, где данные участников попадают
 * в файл, который откроют двойным щелчком на чужой машине. Excel выполняет
 * значение, начинающееся со знака равенства, плюса, минуса или собаки,
 * как формулу. Значит, поле формы на сайте — это способ выполнить
 * выражение на компьютере сотрудника федерации.
 */

describe('ячейка выгрузки реестра', () => {
  it('обычное значение просто берёт в кавычки', () => {
    expect(cell('Иванов Пётр')).toBe('"Иванов Пётр"');
  });

  it('удваивает кавычки внутри значения', () => {
    expect(cell('ООО "Ромашка"')).toBe('"ООО ""Ромашка"""');
  });

  it('обезвреживает формулу', () => {
    // Апостроф впереди — Excel показывает текст и не вычисляет его.
    expect(cell('=HYPERLINK("http://зло","жми")')).toMatch(/^"'=HYPERLINK/);
    expect(cell('+1+1')).toBe(`"'+1+1"`);
    expect(cell('@SUM(A1)')).toBe(`"'@SUM(A1)"`);
  });

  it('обезвреживает минус, но не ломает обычный дефис в середине', () => {
    // Фамилия «-Иванов» безобидна, но начинается с минуса — обезвреживаем.
    expect(cell('-Иванов')).toBe(`"'-Иванов"`);
    // А «Петров-Водкин» трогать незачем: дефис не в начале.
    expect(cell('Петров-Водкин')).toBe('"Петров-Водкин"');
  });

  it('обезвреживает перевод строки и табуляцию в начале', () => {
    // Ими прячут формулу от беглого взгляда: видно пустую ячейку.
    expect(cell('\t=1+1')).toMatch(/^"'/);
  });

  it('пустое значение остаётся пустым', () => {
    expect(cell('')).toBe('""');
  });
});
