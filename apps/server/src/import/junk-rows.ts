/**
 * Строки, которые не являются участниками.
 *
 * Протокол — не только таблица. Ниже участников там стоят итоги («Итого
 * участников: 6»), подписи судейской коллегии («Главный судья ... Иванов
 * И.И.»), сноски со звёздочкой, а в длинных протоколах шапка повторяется
 * на каждой печатной странице. Всё это попадало в получателей: файл 13
 * давал 61 строку вместо участников, файл 14 — 11 вместо 6. На выходе
 * человек получал грамоту «Главному судье» и письмо на пустой адрес.
 *
 * Отбрасываем только то, в чём уверены: повтор самой шапки, строку итога
 * и строку подписи. Сомнительное оставляем — лишний участник в таблице
 * виден и правится, а пропавший теряется молча.
 */

/*
 * Начала строк-итогов и подписей. Проверяются по первой непустой ячейке.
 *
 * Граница слова записана как «дальше не буква», а не `\b`: в JavaScript
 * `\b` считает буквами только латиницу, и после кириллического слова
 * никакой границы не находит — правило молча не срабатывало.
 */
const TOTALS = /^(итого|всего|количество\s+участников|участников\s*:|total)(?!\p{L})/iu;

/** Подписи судейской коллегии и реквизиты бумаги. */
const SIGNATURES =
  /^(главн(ый|ая)\s+(судья|секретарь)|зам\.?\s*главного\s+судьи|судья|секретарь|подпись|расшифровка|м\.\s*п\.|исполнитель)(?!\p{L})/iu;

/** Сноска под таблицей: «* снят с дистанции», «Прим.: ...». */
const FOOTNOTE = /^(\*|прим\.|примечание)/i;

function normalize(value: string): string {
  return value.trim().toLowerCase().replace(/\s+/g, ' ').replace(/ё/g, 'е');
}

/**
 * Строка повторяет шапку.
 *
 * Сравниваем по набору значений, а не по порядку: в повторе шапки на новой
 * странице колонки те же. Одного совпадения мало — «Место» встречается
 * и в данных; требуем не меньше двух и чтобы вся строка состояла
 * из заголовков.
 */
function repeatsHeader(values: string[], header: string[]): boolean {
  const titles = new Set(header.map(normalize).filter(Boolean));
  if (titles.size < 2) return false;

  const filled = values.map(normalize).filter(Boolean);
  if (filled.length < 2) return false;
  return filled.every((value) => titles.has(value));
}

/** Итог, подпись или сноска: смотрим на первую непустую ячейку строки. */
function isTail(values: string[]): boolean {
  const first = values.find((v) => v.trim() !== '')?.trim() ?? '';
  if (!first) return false;
  return TOTALS.test(first) || SIGNATURES.test(first) || FOOTNOTE.test(first);
}

export function isJunkRow(values: string[], header: string[] = []): boolean {
  return repeatsHeader(values, header) || isTail(values);
}

/** Предупреждение о выброшенных строках — молча их терять нельзя. */
export function junkRowsWarning(count: number): string {
  return (
    `Пропущено строк, не похожих на участников: ${count} — ` +
    `итоги, подписи судейской коллегии, сноски и повторы шапки`
  );
}
