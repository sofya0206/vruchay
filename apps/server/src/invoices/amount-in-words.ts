import { numberInWords, pluralForm } from '@gramota/shared';

/**
 * Сумма прописью для счёта.
 *
 * В российском счёте это обязательная строка, и бухгалтер читает её первой:
 * ошибка здесь заметна сразу и подрывает доверие ко всему документу.
 *
 * Само число словами (тысячи, миллионы, склонение по последним двум
 * цифрам) считает общий `numberInWords` из `@gramota/shared` — он писался
 * для этого файла и вынесен, чтобы им же могла пользоваться генерация
 * документов, а не только счета. Здесь остаётся то, что специфично именно
 * деньгам: рубли мужского рода, копейки — числом с ведущим нулём,
 * и заглавная буква в начале строки.
 */

/** Реэкспорт ради обратной совместимости: раньше `plural` жил в этом файле. */
export const plural = pluralForm;

/**
 * Сумма в копейках → «Шестьдесят девять тысяч рублей 00 копеек».
 * Копейки цифрами: так принято в счетах и так их проще сверять.
 */
export function amountInWords(kopecks: number): string {
  if (!Number.isInteger(kopecks) || kopecks < 0) {
    throw new Error('Сумма должна быть целым числом копеек, не меньше нуля');
  }

  const rubles = Math.floor(kopecks / 100);
  const cents = kopecks % 100;

  // Рубль — мужского рода: «один рубль», а не «одна рубль». Только
  // последняя группа (единицы) реагирует на этот род — тысячи внутри
  // суммы остаются «одна тысяча» независимо от рода того, что считают.
  const text = numberInWords(rubles, 'male');
  const capitalized = text.charAt(0).toUpperCase() + text.slice(1);

  return `${capitalized} ${plural(rubles, 'рубль', 'рубля', 'рублей')} ${String(cents).padStart(2, '0')} ${plural(cents, 'копейка', 'копейки', 'копеек')}`;
}
