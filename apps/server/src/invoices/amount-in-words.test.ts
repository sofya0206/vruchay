import { describe, expect, it } from 'vitest';
import { amountInWords, plural } from './amount-in-words';

describe('склонение по числу', () => {
  it('различает единственное, малое и большое', () => {
    expect(plural(1, 'рубль', 'рубля', 'рублей')).toBe('рубль');
    expect(plural(3, 'рубль', 'рубля', 'рублей')).toBe('рубля');
    expect(plural(7, 'рубль', 'рубля', 'рублей')).toBe('рублей');
  });

  it('не путается на числах от одиннадцати до четырнадцати', () => {
    // Главная ловушка: по последней цифре это «рубль», а правильно «рублей».
    expect(plural(11, 'рубль', 'рубля', 'рублей')).toBe('рублей');
    expect(plural(12, 'рубль', 'рубля', 'рублей')).toBe('рублей');
    expect(plural(14, 'рубль', 'рубля', 'рублей')).toBe('рублей');
    expect(plural(111, 'рубль', 'рубля', 'рублей')).toBe('рублей');
    expect(plural(21, 'рубль', 'рубля', 'рублей')).toBe('рубль');
  });
});

describe('сумма прописью', () => {
  it('пишет ноль', () => {
    expect(amountInWords(0)).toBe('Ноль рублей 00 копеек');
  });

  it('пишет наши тарифы', () => {
    expect(amountInWords(2_900_000)).toBe('Двадцать девять тысяч рублей 00 копеек');
    expect(amountInWords(6_900_000)).toBe('Шестьдесят девять тысяч рублей 00 копеек');
    expect(amountInWords(14_900_000)).toBe('Сто сорок девять тысяч рублей 00 копеек');
  });

  it('ставит тысячу в женский род, а рубли в мужской', () => {
    // «Одна тысяча», не «один»; «два рубля», не «две».
    expect(amountInWords(100_000)).toBe('Одна тысяча рублей 00 копеек');
    expect(amountInWords(200_000)).toBe('Две тысячи рублей 00 копеек');
    expect(amountInWords(200)).toBe('Два рубля 00 копеек');
  });

  it('сохраняет копейки цифрами с ведущим нулём', () => {
    expect(amountInWords(105)).toBe('Один рубль 05 копеек');
    expect(amountInWords(1_150)).toBe('Одиннадцать рублей 50 копеек');
    expect(amountInWords(2_221)).toBe('Двадцать два рубля 21 копейка');
  });

  it('справляется с миллионами и сотнями', () => {
    expect(amountInWords(123_456_789)).toBe(
      'Один миллион двести тридцать четыре тысячи пятьсот шестьдесят семь рублей 89 копеек',
    );
  });

  it('отвергает дробные и отрицательные суммы', () => {
    expect(() => amountInWords(10.5)).toThrow();
    expect(() => amountInWords(-100)).toThrow();
  });
});
