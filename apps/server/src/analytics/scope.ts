import type { Prisma } from '@prisma/client';
import { registryWhere } from '../registry/registry-filter';

/**
 * Что аналитика считает выданным и что — отправленным.
 *
 * Одно место на весь модуль, и условие «выданного» не выписано заново,
 * а взято у реестра. Приёмка требует, чтобы цифры сходились с тем,
 * что человек видит руками в таблице; два одинаковых на вид условия
 * рано или поздно разойдутся, и разойдутся молча.
 */

/** Выданное одной организации — ровно то, что показывает её реестр. */
export function issuedByOrg(orgId: string): Prisma.FileWhereInput {
  return registryWhere(orgId, {});
}

/**
 * Выданное по всем организациям сразу — то же условие без `orgId`.
 *
 * Собрано выбрасыванием организации из условия реестра намеренно:
 * воронка по всем обязана считать выданным ровно то же, что каждой
 * организации показывает её собственная таблица.
 */
export function issuedAnywhere(): Prisma.FileWhereInput {
  const { orgId: _orgId, ...common } = registryWhere('', {});
  return common;
}

/**
 * Письмо считается ушедшим, когда его принял почтовый шлюз.
 *
 * Не доставленное входит: оно ушло и вернулось. Не отправившееся — нет.
 * Те же правила, что в сводке реестра, и это не совпадение: «разослано»
 * в двух разделах кабинета обязано означать одно и то же.
 */
