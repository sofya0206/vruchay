type Cell = string | number | { time: number; decimals?: number } | { date: Date } | null;

interface SheetSpec {
  file: string;
  sheetName: string;
  /** Строки как есть: строка — массив ячеек. */
  rows: Cell[][];
  /** Диапазоны объединения в адресах Excel: 'B2:C2'. */
  merges?: string[];
  /** Ширина колонок — только чтобы файл открывался по-человечески. */
  widths?: number[];
}

/** Секунды дистанции как доля суток — так время лежит в Excel на самом деле. */
const time = (seconds: number, decimals = 2) => ({ time: seconds, decimals });

function build(spec: SheetSpec): ExcelJS.Workbook {
  const wb = new ExcelJS.Workbook();
  const ws = wb.addWorksheet(spec.sheetName);

  spec.rows.forEach((row, r) => {
    row.forEach((value, c) => {
      if (value === null) return;
      const cell = ws.getCell(r + 1, c + 1);
      if (typeof value === 'object' && 'time' in value) {
        const decimals = value.decimals ?? 2;
        cell.value = value.time / 86400;
        // Формат без года и дня — по нему парсер и понимает, что это
        // длительность, а не дата: в самой ячейке лежит одно и то же число.
        cell.numFmt = value.time >= 60 ? `mm:ss.${'0'.repeat(decimals)}` : `ss.${'0'.repeat(decimals)}`;
      } else if (typeof value === 'object' && 'date' in value) {
        cell.value = value.date;
        cell.numFmt = 'dd.mm.yyyy';
      } else {
        cell.value = value;
      }
    });
  });

  for (const range of spec.merges ?? []) ws.mergeCells(range);
  if (spec.widths) spec.widths.forEach((w, i) => (ws.getColumn(i + 1).width = w));
  return wb;
}

