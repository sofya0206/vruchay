async function main(): Promise<void> {
  await mkdir(OUT_DIR, { recursive: true });
  for (const spec of SPECS) {
    const wb = build(spec);
    const buffer = await wb.xlsx.writeBuffer();
    await writeFile(path.join(OUT_DIR, spec.file), Buffer.from(buffer));
    console.log(`✓ ${spec.file}`);
  }
  console.log(`\nГотово: ${SPECS.length} файлов в ${OUT_DIR}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
