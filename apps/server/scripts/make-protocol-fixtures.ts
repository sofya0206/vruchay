/**
 * Генератор синтетических протоколов соревнований: docs/fixtures/protocols/*.xlsx
 *
 *   pnpm --filter @gramota/server fixtures:protocols
 *
 * Запускается руками и редко. Файлы коммитятся: на них держатся тесты
 * парсера, и они должны меняться только вместе с генератором — иначе
 * «поправил фикстуру, чтобы тест позеленел» станет обычным делом.
 *
 * Протоколы синтетические, потому что настоящие — это персональные данные
 * несовершеннолетних спортсменов, и класть их в репозиторий нельзя ни при
 * каких обстоятельствах. Фамилии выдуманы, совпадения случайны.
 *
 * Чего синтетика заведомо не воспроизводит — в docs/fixtures/protocols/ограничения.md.
 * Этот список обязателен к прочтению перед выводом «парсер готов».
 */
import { mkdir, writeFile } from 'node:fs/promises';
