-- Одно живое письмо на пару «материал + адрес» внутри потока.
--
-- Защита от повторной отправки до сих пор жила только в коде: перед рассылкой
-- служба читала журнал и выбрасывала адреса, которым письмо уже уходило.
-- Между этим чтением и вставкой есть окно, и человек, нажавший «Отправить»
-- дважды, попадает в него легко: оба запроса читают пустой список и оба
-- создают письма. Участник получает два одинаковых письма, а с общего домена
-- уходит двойной объём.
--
-- Индекс частичный намеренно. Обычный уникальный сломал бы переотправку
-- недоставленных: resendFailed создаёт новое письмо на тот же адрес в том же
-- потоке — и обязан, потому что журнал должен помнить и первую попытку,
-- и чем она кончилась. Прошлая попытка лежит в bounced/failed, то есть вне
-- индекса, и новой не мешает.
--
-- Два уточнения к условию, которых не видно, пока смотришь на одну задачу:
--
--  1. `to_email <> ''` — иначе индекс ломает ночную уборку сроков хранения.
--     Она стирает адрес участника через год, оставляя статус доставки: два
--     доставленных письма разным людям по одному материалу превращаются
--     в две одинаковые строки (материал, '', поток) и вторая не проходит.
--     Обезличенному письму отправлять всё равно некуда — по той же причине
--     его пропускает и resendFailed.
--
--  2. `lower(to_email)` — адрес нечувствителен к регистру, и без этого
--     «Ivanov@…» обходил бы защиту. Так же сделан и соседний частичный
--     индекс tilda_requests_one_per_email.
--
-- Письма без материала (document_id IS NULL) индекс не трогает: в Postgres
-- NULL не равен NULL, и служебная почта под ограничение не попадает.
--
-- Откат:
--   DROP INDEX "emails_document_to_kind_live";

-- ─── Существующие дубли ────────────────────────────────────────────────────
--
-- Индекс не встанет поверх данных, которые ему противоречат, а противоречить
-- могут ровно те строки, которые он и создан не допускать, — следы двойного
-- нажатия до этой миграции. Оставляем самое раннее письмо группы, остальные
-- удаляем: запись о письме без самого письма журналу не нужна, а миграция,
-- падающая посреди выката, хуже.
--
-- Сколько удалено — печатаем в вывод миграции: если число окажется не нулём,
-- это и есть счёт участникам, получившим одно и то же письмо дважды.
DO $$
DECLARE
  removed integer;
BEGIN
  WITH ranked AS (
    SELECT "id",
           row_number() OVER (
             PARTITION BY "document_id", lower("to_email"), "kind"
             ORDER BY "queued_at", "id"
           ) AS n
    FROM "emails"
    WHERE "status" IN ('queued', 'sent', 'delivered', 'opened')
      AND "to_email" <> ''
      AND "document_id" IS NOT NULL
  )
  DELETE FROM "emails" WHERE "id" IN (SELECT "id" FROM ranked WHERE n > 1);

  GET DIAGNOSTICS removed = ROW_COUNT;
  IF removed > 0 THEN
    RAISE NOTICE 'Повторных писем удалено: %', removed;
  END IF;
END $$;

-- ─── Сам индекс ────────────────────────────────────────────────────────────

CREATE UNIQUE INDEX "emails_document_to_kind_live"
  ON "emails" ("document_id", lower("to_email"), "kind")
  WHERE "status" IN ('queued', 'sent', 'delivered', 'opened') AND "to_email" <> '';
