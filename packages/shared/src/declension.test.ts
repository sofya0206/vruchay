import { describe, expect, it } from 'vitest';
import { declineFullName } from './declension';

/*
 * Склонение ФИО. Проверяем не столько удачные случаи, сколько границу:
 * где мы обязаны отступить и вернуть строку нетронутой. Ошибка здесь
 * печатается на грамоте и вручается человеку при всех.
 */

const dat = (s: string) => declineFullName(s, 'dative');
const gen = (s: string) => declineFullName(s, 'genitive');

describe('дательный падеж — «награждается кому»', () => {
  it('склоняет полное ФИО мужчины', () => {
    expect(dat('Иванов Пётр Ильич')).toBe('Иванову Петру Ильичу');
  });

  it('склоняет полное ФИО женщины', () => {
    expect(dat('Петрова Мария Ивановна')).toBe('Петровой Марии Ивановне');
  });

  it('сохраняет порядок слов «Имя Фамилия», если так и написали', () => {
    // Меняя порядок, мы поправляли бы человека там, где его не просили.
    expect(dat('Мария Петрова')).toBe('Марии Петровой');
  });

  it('склоняет «Фамилия Имя» — как пишут в протоколах', () => {
    expect(dat('Иванов Пётр')).toBe('Иванову Петру');
  });

  it('пол берёт из отчества, а не из имени', () => {
    // «Женя» само по себе не отвечает на вопрос о поле, отчество — отвечает.
    expect(dat('Смирнов Женя Петрович')).toBe('Смирнову Жене Петровичу');
    expect(dat('Смирнова Женя Петровна')).toBe('Смирновой Жене Петровне');
  });

  it('справляется с одной фамилией', () => {
    expect(dat('Иванов')).toBe('Иванову');
  });

  it('справляется с одним именем', () => {
    expect(dat('Пётр')).toBe('Петру');
  });

  it('не путает женское имя на «на» с отчеством', () => {
    // Елена, Полина, Анна оканчиваются на «на» — но отчествами не являются.
    expect(dat('Соколова Елена')).toBe('Соколовой Елене');
  });
});

describe('родительный падеж', () => {
  it('склоняет полное ФИО', () => {
    expect(gen('Иванов Пётр Ильич')).toBe('Иванова Петра Ильича');
  });
});

describe('когда склонять нельзя — возвращаем как есть', () => {
  it('латиница остаётся нетронутой', () => {
    expect(dat('John Smith')).toBe('John Smith');
  });

  it('смешанная строка остаётся нетронутой', () => {
    expect(dat('Иванов Ivan')).toBe('Иванов Ivan');
  });

  it('больше трёх слов не разбираем', () => {
    // Двойные фамилии, «оглы», приставки: надёжно не разобрать,
    // а испортить — легко.
    const long = 'Мамедов Мамед Мамед оглы';
    expect(dat(long)).toBe(long);
  });

  it('пустая строка возвращается как была', () => {
    expect(dat('')).toBe('');
    expect(dat('   ')).toBe('   ');
  });

  it('цифры в строке отменяют склонение', () => {
    expect(dat('Иванов 1')).toBe('Иванов 1');
  });

  it('инициалы не трогаем, фамилию склоняем', () => {
    expect(dat('Иванов П.И.')).toBe('Иванову П.И.');
  });
});

describe('фамилии, которые склоняются не как все', () => {
  it('несклоняемые оставляет в покое', () => {
    // «Белых», «Петренко», «Гончарук» у женщин не изменяются — и это
    // не наша недоработка, а правило языка.
    expect(dat('Белых Иван')).toBe('Белых Ивану');
    expect(dat('Петренко Олег')).toBe('Петренко Олегу');
    expect(dat('Гончарук Дарья')).toBe('Гончарук Дарье');
  });

  it('двойную фамилию склоняет по обеим частям', () => {
    expect(dat('Иванов-Петров Пётр')).toBe('Иванову-Петрову Петру');
  });

  it('нерусскую по форме фамилию склоняет по полу владельца', () => {
    // Ким мужчина склоняется, Ким женщина — нет.
    expect(dat('Ким Сергей')).toBe('Киму Сергею');
    expect(dat('Ким Ольга')).toBe('Ким Ольге');
  });
});

describe('пол, когда отчества нет', () => {
  it('берёт пол из фамилии', () => {
    expect(dat('Иванов Саша')).toBe('Иванову Саше');
    expect(dat('Иванова Саша')).toBe('Ивановой Саше');
  });

  it('мужское имя на «а» не считает женским', () => {
    expect(dat('Иванов Никита')).toBe('Иванову Никите');
    expect(dat('Кузнецов Илья Никитич')).toBe('Кузнецову Илье Никитичу');
  });

  it('«Любовь» — женское, «Игорь» — мужское', () => {
    expect(dat('Соколова Любовь')).toBe('Соколовой Любови');
    expect(dat('Соколов Игорь')).toBe('Соколову Игорю');
  });
});

describe('известное ограничение', () => {
  it('порядок «Имя Фамилия» узнаётся по приметам фамилии', () => {
    // Суффиксы -ов, -ев, -ин, -ский, -енко, -ук покрывают подавляющее
    // большинство русских фамилий, и такие пары разбираются верно.
    expect(dat('Иван Петренко')).toBe('Ивану Петренко');
    expect(dat('Мария Петрова')).toBe('Марии Петровой');
  });

  it('без примет держимся порядка списков — «Фамилия Имя»', () => {
    // «Илья Муромец»: ни одно слово не похоже на фамилию по суффиксу,
    // и первое принимается за фамилию — как в протоколах и приказах.
    // Разбор получается неверный, и это цена соглашения: обратное
    // правило ломало бы куда более частое «Мороз Пётр».
    expect(dat('Илья Муромец')).toBe('Илье Муромецу');
  });
});

describe('мелочи ввода', () => {
  it('лишние пробелы схлопываются', () => {
    expect(dat('  Иванов   Пётр  ')).toBe('Иванову Петру');
  });

  it('буква «ё» не ломает разбор', () => {
    expect(dat('Фёдоров Пётр')).toBe('Фёдорову Петру');
  });
});
