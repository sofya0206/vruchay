/**
 * Сроки хранения, о которых знают обе стороны.
 *
 * Здесь только то, что сервер применяет, а кабинет показывает человеку.
 * Разъехавшись, эти числа дают худший из возможных видов ошибки: подпись
 * обещает одно, а система делает другое, и заметно это становится, когда
 * что-то уже стёрлось.
 */

/**
 * Сколько документ лежит в корзине до окончательного удаления.
 *
 * Неделя — компромисс: за это время замечают, что выбросили нужное, а
 * наградные документы с фамилиями не копятся месяцами после того, как
 * организация решила их не хранить (ч. 7 ст. 5 152-ФЗ — не дольше, чем
 * этого требует цель).
 */
export const TRASH_DAYS = 7;

/** Сколько дней осталось документу в корзине. Ноль — сегодня ночью исчезнет. */
export function daysLeftInTrash(deletedAt: Date | string, now: Date = new Date()): number {
  const deleted = typeof deletedAt === 'string' ? new Date(deletedAt) : deletedAt;
  const dayMs = 24 * 60 * 60 * 1000;
  const passed = Math.floor((now.getTime() - deleted.getTime()) / dayMs);
  return Math.max(0, TRASH_DAYS - passed);
}
