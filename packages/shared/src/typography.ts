/**
 * Русская типографика для подставленных значений.
 *
 * Правило одно и оно узкое: правим то, что подставилось из таблицы,
 * и не трогаем то, что человек набрал в самом шаблоне. Причина в том,
 * чем отличаются эти два текста. Шаблон набирают глазами, глядя на лист:
 * там уже стоит ровно то, что человек хотел, и «улучшать» его за него —
 * значит спорить с автором. А значения приезжают из чужой таблицы,
 * заполненной в Excel: там «г.Челябинск» без пробела, «И.И.Иванов»
 * без пробелов и дефис вместо тире, и на грамоте это видно.
 *
 * Почему не библиотека. `typograf` умеет на порядок больше, чем нужно,
 * и как раз это и мешает: у него полсотни правил, часть которых
 * переписывает текст сильнее, чем мы вправе. Но решающее — не объём
 * правил, а место применения: проверка списка прогоняет подстановку
 * на десяти тысячах строк и укладывается в единицы секунд (её бюджет
 * закреплён отдельным тестом). Регулярки `typograf` в этой петле
 * заметны, а 600 КБ его исходников уехали бы и в сервер, и в браузер.
 *
 * Здесь ровно те правила, которые видно на наградном документе.
 * Каждое проверено тестом, и каждое обязано быть устойчивым к повтору:
 * значение прогоняется через них и при измерении, и при печати, и оба
 * раза обязаны дать один и тот же текст — иначе «влезает» и «влезло»
 * разойдутся.
 */

/** Неразрывный пробел: в вёрстке он и переносу мешает, и ширину имеет. */
export const NBSP = ' ';
/** Узкий неразрывный — между инициалами, чтобы «И. И.» не разъезжалось. */
export const NNBSP = ' ';

/**
 * Однобуквенные предлоги и союзы.
 *
 * Висящий в конце строки одинокий предлог — первое, что замечает глаз
 * на грамоте. Список закрытый: это все однобуквенные слова русского
 * языка, которые встречаются в наградных формулировках.
 */
const SHORT_WORDS = 'аибвкосуяжё';

/**
 * Слова, перед которыми пробел неразрывен: «г.» города, «руб.» суммы,
 * «%» процентов. Отрывать их от числа или названия нельзя — читается
 * как две разные строки.
 */
const GLUE_AFTER = ['г', 'гг', 'руб', 'коп', 'тыс', 'млн', 'млрд', 'кв', 'ул', 'д', 'стр'];

/** Пробелы, которые правила считают «обычными»: перевод строки не трогаем. */
const SPACE = '[ \\t\\u00A0\\u202F]';

export interface TypographyOptions {
  /** Кавычки-ёлочки вместо машинописных. */
  quotes?: boolean;
  /** Тире вместо дефиса там, где дефис стоит вместо тире. */
  dashes?: boolean;
  /** Неразрывные пробелы: предлоги, инициалы, единицы. */
  nbsp?: boolean;
}

const ALL: Required<TypographyOptions> = { quotes: true, dashes: true, nbsp: true };

/**
 * Причесать подставленное значение.
 *
 * Порядок правил не случаен: кавычки ставим до тире, иначе дефис внутри
 * кавычек («Научно-практический») успевал бы стать тире. Инициалы
 * — до предлогов, иначе одиночная буква инициала считалась бы предлогом.
 */
export function typographRu(value: string, options: TypographyOptions = ALL): string {
  const opts = { ...ALL, ...options };
  let out = value;

  if (opts.quotes) out = quotes(out);
  if (opts.dashes) out = dashes(out);
  if (opts.nbsp) {
    out = initials(out);
    out = glue(out);
    out = shortWords(out);
  }

  return out;
}

/**
 * Машинописные кавычки — ёлочками, вложенные — лапками.
 *
 * Открывающая отличается от закрывающей по соседям: после начала строки,
 * пробела или открывающей скобки кавычка открывающая, иначе закрывающая.
 * Этого правила хватает на «АО «Звёздочка»» и на «школа №1 «Радуга»».
 *
 * Уже расставленные ёлочки и лапки считаем вместе с машинописными —
 * иначе второй прогон по собственному результату закрывал бы вложенную
 * лапку ёлочкой. Прогонов ровно два (измерение и печать), и они обязаны
 * дать один и тот же текст.
 */
function quotes(value: string): string {
  let depth = 0;
  let out = '';

  for (const raw of value) {
    // Английские «лапки» приводим к машинописным: в русских данных они
    // приезжают из Word и означают ту же кавычку, а не свою собственную.
    const char = raw === '“' || raw === '”' ? '"' : raw;

    if (char === '«' || char === '„') {
      depth++;
      out += char;
      continue;
    }
    if (char === '»') {
      depth = Math.max(depth - 1, 0);
      out += char;
      continue;
    }
    if (char !== '"') {
      out += char;
      continue;
    }

    const before = out.at(-1) ?? '';
    const opening = before === '' || /[\s([{«„]/u.test(before);

    if (opening) {
      out += depth === 0 ? '«' : '„';
      depth++;
    } else {
      depth = Math.max(depth - 1, 0);
      out += depth === 0 ? '»' : '“';
    }
  }

  return out;
}

/**
 * Дефис тире не заменяем — заменяем только дефис, стоящий вместо тире.
 *
 * Отличает их положение: тире отбито пробелами с обеих сторон
 * («Иванов - победитель»), дефис в слове не отбит («научно-практический»),
 * и путать их нельзя — «Научно — практический центр» это уже
 * другое название. Отдельно ставим тире в диапазонах чисел
 * («17-19 июня» → «17–19 июня»), но только среднее, а не длинное.
 *
 * Пробел перед тире неразрывный: тире, начинающее строку, читается как
 * маркер списка, а не как знак предложения.
 */
function dashes(value: string): string {
  return value
    .replace(new RegExp(`(\\S)${SPACE}+-${SPACE}+`, 'gu'), `$1${NBSP}— `)
    .replace(new RegExp(`(\\d)${SPACE}?-${SPACE}?(\\d)`, 'gu'), '$1–$2');
}

/**
 * Инициалы: «И.И.Иванов» и «И. И. Иванов» — в «И. И. Иванов».
 *
 * Разрывать инициалы нельзя ни между собой, ни от фамилии: «И. И.» в конце
 * строки и «Иванов» в начале следующей читаются как два разных человека.
 * Пробел узкий, потому что обычный между точкой и буквой выглядит дырой.
 *
 * Одним правилом, а не двумя: два последовательных правила на втором
 * прогоне переклеивали уже склеенное — узкий пробел тоже пробел,
 * и второе правило видело его как разрыв.
 */
function initials(value: string): string {
  return value.replace(
    new RegExp(`(\\p{Lu})\\.${SPACE}*(?=\\p{Lu}\\.|\\p{Lu}\\p{Ll})`, 'gu'),
    `$1.${NNBSP}`,
  );
}

/**
 * Сокращения и знаки, которые нельзя отрывать от своего слова.
 *
 * «г. Челябинск» — пробел неразрывный после сокращения, «120 руб.»
 * и «100 %» — перед. Заодно чиним «г.Челябинск» без пробела: в таблицах
 * его пишут так постоянно, а на грамоте это выглядит опечаткой.
 *
 * Границу слова ищем просмотром назад, а не `\b`: в JavaScript `\b`
 * считает буквами только латиницу, и перед кириллическим «г» границы
 * для него не существует — правило молча не срабатывало ни разу.
 */
function glue(value: string): string {
  const list = GLUE_AFTER.join('|');
  return value
    .replace(new RegExp(`(?<!\\p{L})(${list})\\.${SPACE}*(?=\\p{L})`, 'giu'), `$1.${NBSP}`)
    .replace(new RegExp(`(\\d)${SPACE}+(?=(?:${list})\\.)`, 'giu'), `$1${NBSP}`)
    .replace(new RegExp(`(\\d)${SPACE}*%`, 'gu'), `$1${NBSP}%`)
    .replace(new RegExp(`№${SPACE}*(?=\\d)`, 'gu'), `№${NBSP}`);
}

/** Одинокий предлог не остаётся в конце строки. */
function shortWords(value: string): string {
  return value.replace(
    new RegExp(`(^|[\\s(«„])([${SHORT_WORDS}])${SPACE}+`, 'giu'),
    `$1$2${NBSP}`,
  );
}
