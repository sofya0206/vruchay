/**
 * Транслитерация ФИО латиницей — для документов на английском.
 *
 * Часть сертификатов выпускается на латинице или сразу на двух языках:
 * участник международного турнира, диплом для зарубежного вуза. Сейчас
 * организатор заводит ради этого вторую колонку и переписывает в неё
 * триста фамилий руками — ровно то же дублирование, из-за которого
 * появилось склонение в `declension.ts`.
 *
 * Правило файла то же, что там: **в сомнении не занимаемся
 * самодеятельностью**. Только здесь сомневаться почти негде — таблица
 * однозначна для любой кириллической буквы, — поэтому и аппарата
 * сомнений (`DeclensionDoubt`, `DeclensionConfidence`) тут нет. Всё,
 * что не кириллица, проходит насквозь нетронутым: латинское имя,
 * дефис, точка, цифра в «Иванов-2» останутся собой.
 *
 * Ни падежа, ни пола транслитерация не знает и знать не должна:
 * это посимвольная замена, а не грамматика. Отсюда и отсутствие
 * `petrovich` в импортах.
 *
 * Стандартов два, и они правда разные:
 *
 *  — **ГОСТ 7.79-2000, система Б** — библиотечный и делопроизводственный.
 *    Обходится без диакритики за счёт буквосочетаний: «х» → `x`,
 *    «щ» → `shh`, «ю» → `yu`.
 *  — **ICAO Doc 9303** — то, что напечатано в загранпаспорте. Именно
 *    его ждёт зарубежная сторона, когда сверяет диплом с паспортом:
 *    «х» → `kh`, «щ» → `shch`, «ю» → `iu`.
 *
 * Одной таблицей их не покрыть: расходятся Ц, Х, Щ, Ъ, Ю, Я, а заодно
 * Ё, Й и Э. Поэтому две функции, а не одна с флагом, — на грамоте
 * должно быть видно из имени переменной, какой стандарт выбран.
 */

/** Таблица замен: строчная кириллическая буква → латиница. */
type TranslitTable = Record<string, string>;

/**
 * ГОСТ 7.79-2000, система Б.
 *
 * Строгая запись стандарта помечает «ъ» кавычкой, «ь» апострофом,
 * а «ы» и «э» — апострофом после буквы (`y'`, `e'`). В имени на
 * дипломе эти знаки только мешают: `Igor'` читается как опечатка,
 * а кавычка внутри слова ломает половину чужих систем, куда этот
 * документ потом попадёт. Поэтому здесь только латинские буквы:
 * «ъ» и «ь» опускаются, «ы» → `y`, «э» → `e`.
 */
const GOST: TranslitTable = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'yo', ж: 'zh',
  з: 'z', и: 'i', й: 'j', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o',
  п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'x', ц: 'cz',
  ч: 'ch', ш: 'sh', щ: 'shh', ъ: '', ы: 'y', ь: '', э: 'e',
  ю: 'yu', я: 'ya',
};

/**
 * ICAO Doc 9303 — та самая таблица, по которой пишут имя
 * в загранпаспорте.
 */
const ICAO: TranslitTable = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh',
  з: 'z', и: 'i', й: 'i', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o',
  п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'kh', ц: 'ts',
  ч: 'ch', ш: 'sh', щ: 'shch', ъ: 'ie', ы: 'y', ь: '', э: 'e',
  ю: 'iu', я: 'ia',
};

/**
 * Буквы, перед которыми ГОСТ пишет «ц» как `c`, а не `cz`.
 *
 * Единственное правило стандарта, зависящее от соседа: «цирк» → `circ`,
 * но «Кузнецов» → `Kuzneczov`. Выглядит неожиданно, и всё же это
 * буква стандарта, а не наша вольность.
 */
const C_AFTER_TS = new Set(['и', 'е', 'й', 'ь']);

/** Кириллица — по её наличию решаем, есть ли что транслитерировать. */
const CYRILLIC = /[А-Яа-яЁё]/;

/** Строчная кириллица — по её отсутствию узнаём запись капсом. */
const HAS_LOWERCASE = /[а-яё]/;

/**
 * ФИО латиницей по ГОСТ 7.79-2000 (система Б).
 *
 * Пустая строка и всё нерусское возвращаются как есть, без исключений:
 * английское имя в колонке «ФИО» — не ошибка, а законный случай.
 */
export function transliterateGost(fullName: string): string {
  return transliterate(fullName, GOST, true);
}

/** ФИО латиницей по ICAO Doc 9303 — как в загранпаспорте. */
export function transliterateIcao(fullName: string): string {
  return transliterate(fullName, ICAO, false);
}

function transliterate(fullName: string, table: TranslitTable, gostC: boolean): string {
  if (!fullName || !CYRILLIC.test(fullName)) return fullName;

  // Слова разбираем по отдельности: «ПЕТРОВ Иван» — обычная запись
  // в списках, и капс одного слова не должен делать капсом всё имя.
  return fullName
    .split(/(\s+)/)
    .map((word) => (CYRILLIC.test(word) ? transliterateWord(word, table, gostC) : word))
    .join('');
}

function transliterateWord(word: string, table: TranslitTable, gostC: boolean): string {
  // «ИВАНОВ» пишем как `IVANOV`, а не `Ivanov`: капс в списке участников
  // ставят намеренно, и сбрасывать его мы не вправе.
  const upper = !HAS_LOWERCASE.test(word);

  let out = '';
  for (let i = 0; i < word.length; i += 1) {
    const char = word[i];
    const lower = char.toLowerCase();
    let repl = table[lower];

    if (repl === undefined) {
      // Не кириллица: дефис в «Тер-Петросян», точка в «П.», цифра.
      out += char;
      continue;
    }

    if (gostC && lower === 'ц' && C_AFTER_TS.has((word[i + 1] ?? '').toLowerCase())) {
      repl = 'c';
    }

    if (char !== lower) repl = upper ? repl.toUpperCase() : capitalize(repl);
    out += repl;
  }
  return out;
}

/** Только первая буква замены: «Щ» в начале слова — это `Shh`, не `SHH`. */
function capitalize(value: string): string {
  return value ? value[0].toUpperCase() + value.slice(1) : value;
}
