/**
 * Транслитерация ФИО — чтобы на англоязычном (или двуязычном) сертификате
 * имя не оставалось кириллицей и не требовало отдельной колонки, которую
 * организатор заполняет транслитом вручную. Та же ручная работа, ради
 * которой заведено склонение в `declension.ts`, — здесь для латиницы.
 *
 * В отличие от склонения, здесь решать нечего: таблица однозначна для
 * любой кириллической буквы, падеж и пол ей не нужны, а библиотека
 * `petrovich` — тем более. Поэтому развесистого аппарата сомнений
 * (`DeclensionDoubt`, `DeclensionConfidence`) тут нет — не потому что
 * правило файла «в сомнении не занимаемся самодеятельностью» не
 * действует, а потому что сомневаться не в чем: для буквы, которой нет
 * в таблице (латиница, цифра, дефис, пробел), самодеятельность — это
 * как раз попытка её куда-то преобразовать. Правильный ответ — оставить
 * как есть, и это делает сам механизм замены, без отдельной проверки.
 *
 * Зачем таблиц две. ГОСТ 7.79-2000 (система Б) и стандарт загранпаспорта
 * (ICAO Doc 9303 в редакции приказа МВД № 211) расходятся на буквах
 * Ц, Х, Щ, Ъ, Ь, Ю, Я — как раз тех, что чаще всего встречаются
 * в русских фамилиях. Взять одну таблицу на оба случая означало бы,
 * что «Кузьмич» в загранпаспорте и на дипломе пишутся по-разному
 * при любом выборе — и постоянно приходится нашей ошибкой то одно,
 * то другое.
 */

/** Один символ кириллицы → одна или несколько латинских букв (нижний регистр). */
type TransliterationTable = Record<string, string>;

/**
 * ГОСТ 7.79-2000, система Б — без диакритики, только буквы ASCII
 * и апостроф/кавычка вместо твёрдого и мягкого знака. Раньше был
 * стандартом библиотечной и научной транслитерации; годится там, где
 * нужна не государственная бумага, а просто читаемая латиница на бланке.
 */
const GOST_TABLE: TransliterationTable = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'yo', ж: 'zh', з: 'z',
  и: 'i', й: 'j', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r',
  с: 's', т: 't', у: 'u', ф: 'f', х: 'x', ц: 'cz', ч: 'ch', ш: 'sh',
  щ: 'shh', ъ: '"', ы: "y'", ь: "'", э: "e'", ю: 'yu', я: 'ya',
};

/**
 * ICAO Doc 9303 — то, что печатают в машиночитаемой зоне и латинской
 * строке настоящего загранпаспорта (приказ МВД № 211 от 26.03.2014).
 * Твёрдый знак не отбрасывается, а передаётся буквосочетанием «ie» —
 * так, как это делает служба, выпускающая паспорт; мягкий знак, наоборот,
 * не передаётся вовсе.
 */
const ICAO_TABLE: TransliterationTable = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z',
  и: 'i', й: 'i', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r',
  с: 's', т: 't', у: 'u', ф: 'f', х: 'kh', ц: 'ts', ч: 'ch', ш: 'sh',
  щ: 'shch', ъ: 'ie', ы: 'y', ь: '', э: 'e', ю: 'iu', я: 'ia',
};

/**
 * Заменяет по таблице посимвольно, буква за буквой.
 *
 * Буквы, которых в таблице нет — латиница, цифры, дефис, точка, пробел, —
 * идут в результат без изменений: транслитерировать их не наше дело,
 * а гадать, что с ними делать, значит рисковать испортить то, что человек
 * написал сознательно (например, уже готовую латинскую часть двойной
 * фамилии).
 *
 * Регистр буквы переносится на результат: строчная кириллица даёт
 * строчную латиницу, заглавная — латиницу с заглавной первой буквой
 * («Ж» из «zh» станет «Zh», а не «ZH» и не «zh»). Так фамилия из одного
 * слова транслитерируется в слово с одной заглавной буквой, как её и
 * пишут.
 */
function transliterate(fullName: string, table: TransliterationTable): string {
  if (!fullName) return fullName;

  let result = '';
  for (const char of fullName) {
    const lower = char.toLowerCase();
    const replacement = table[lower];
    if (replacement === undefined) {
      result += char;
      continue;
    }
    const isUpper = char !== lower;
    result += isUpper && replacement
      ? replacement[0].toUpperCase() + replacement.slice(1)
      : replacement;
  }
  return result;
}

/**
 * ФИО латиницей по ГОСТ 7.79-2000, система Б.
 *
 * «Кузьмич» → «Kuz'mich», «Объедков» → «Ob"edkov». Апостроф и кавычка —
 * не опечатка: система Б рассчитана на ASCII без диакритики, и твёрдый/
 * мягкий знак в ней передаются пунктуацией, а не выбрасываются, — так
 * запись остаётся обратимой.
 */
export function transliterateGost(fullName: string): string {
  return transliterate(fullName, GOST_TABLE);
}

/**
 * ФИО латиницей, как в загранпаспорте (ICAO Doc 9303 / приказ МВД № 211).
 *
 * «Кузьмич» → «Kuzmich» (мягкий знак пропадает), «Объедков» → «Obieedkov»
 * (твёрдый знак не пропадает, а становится «ie» — так его передаёт сам
 * стандарт). Эта запись предсказуема ровно потому, что она чужая — её
 * печатает МВД, а не мы; наше дело — повторить её без самодеятельности,
 * посимвольно.
 */
export function transliterateIcao(fullName: string): string {
  return transliterate(fullName, ICAO_TABLE);
}
