/**
 * Целое число прописью — «двадцать один документ», а не «21 документ»,
 * там, где документ читают, а не сверяют по таблице.
 *
 * Раньше это было зашито внутрь суммы для счёта (`amount-in-words.ts`
 * в `apps/server`) и умело говорить только о рублях и копейках. Здесь —
 * та же арифметика чисел словами, без денег: тысячи, миллионы, милли-
 * арды и согласование последней группы с тем словом, что идёт следом
 * («документ», «место», «штука» — род у них разный, и число должно
 * ему соответствовать: «одна тысяча», но «один документ» и «одно место»).
 *
 * Две ловушки те же, что и у суммы, потому что число внутри одно и то же:
 * «тысяча» — существительное женского рода, и стоящее рядом «один»
 * обязано быть «одна» независимо от того, что считают («одна тысяча
 * рублей», «одна тысяча документов»); а согласование считающего слова
 * зависит от последних двух цифр числа, а не только от последней
 * («одиннадцать документов», не «одиннадцать документ»).
 */

/** Род слова, которое идёт после числа: он определяет форму «один/одна/одно». */
export type NumberGender = 'male' | 'female' | 'neuter';

const ONES: Record<NumberGender, string[]> = {
  male: ['', 'один', 'два', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять'],
  female: ['', 'одна', 'две', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять'],
  neuter: ['', 'одно', 'два', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять'],
};
const TEENS = [
  'десять', 'одиннадцать', 'двенадцать', 'тринадцать', 'четырнадцать',
  'пятнадцать', 'шестнадцать', 'семнадцать', 'восемнадцать', 'девятнадцать',
];
const TENS = [
  '', '', 'двадцать', 'тридцать', 'сорок', 'пятьдесят',
  'шестьдесят', 'семьдесят', 'восемьдесят', 'девяносто',
];
const HUNDREDS = [
  '', 'сто', 'двести', 'триста', 'четыреста', 'пятьсот',
  'шестьсот', 'семьсот', 'восемьсот', 'девятьсот',
];

/** Разряды тысяч выше единиц: род задаёт само слово, а не то, что считают. */
const SCALES: { threshold: number; one: string; few: string; many: string; gender: NumberGender }[] = [
  { threshold: 1_000_000_000, one: 'миллиард', few: 'миллиарда', many: 'миллиардов', gender: 'male' },
  { threshold: 1_000_000, one: 'миллион', few: 'миллиона', many: 'миллионов', gender: 'male' },
  { threshold: 1000, one: 'тысяча', few: 'тысячи', many: 'тысяч', gender: 'female' },
];

/**
 * Выбор формы по последним двум цифрам: 1 → «документ», 2–4 → «документа»,
 * иначе «документа» → «документов». Ловушка та же, что у денег: 11–14 —
 * всегда «many», хотя последняя цифра совпадает с «один».
 */
export function pluralForm(n: number, one: string, few: string, many: string): string {
  const mod100 = n % 100;
  if (mod100 >= 11 && mod100 <= 14) return many;
  const mod10 = n % 10;
  if (mod10 === 1) return one;
  if (mod10 >= 2 && mod10 <= 4) return few;
  return many;
}

/** Группа до 999 словами, в указанном роде («один»/«одна»/«одно», «два»/«две»/«два»). */
function groupToWords(n: number, gender: NumberGender): string[] {
  const parts: string[] = [];
  const h = Math.floor(n / 100);
  const rest = n % 100;
  if (h) parts.push(HUNDREDS[h]);
  if (rest >= 10 && rest <= 19) {
    parts.push(TEENS[rest - 10]);
  } else {
    const t = Math.floor(rest / 10);
    const o = rest % 10;
    if (t) parts.push(TENS[t]);
    if (o) parts.push(ONES[gender][o]);
  }
  return parts;
}

/**
 * Целое неотрицательное число прописью, в именительном падеже.
 *
 * `gender` определяет форму только последней (самой младшей) группы —
 * той, что стоит рядом со считаемым словом: «один документ» (male),
 * «одна попытка» (female), «одно место» (neuter). Группы постарше —
 * тысячи, миллионы, миллиарды — согласуются с собственным словом
 * («тысяча» женского рода, «миллион» и «миллиард» — мужского) и от
 * этого параметра не зависят: «двадцать одна тысяча документов»,
 * а не «двадцать один тысяча».
 *
 * Строка возвращается без заглавной буквы: где число стоит в середине
 * фразы («получил 21 документ» → «получил двадцать один документ»),
 * капитализация была бы лишней. Там, где число открывает предложение
 * (как сумма счёта), капитализирует вызывающий код — см. `amountInWords`.
 */
export function numberInWords(n: number, gender: NumberGender = 'male'): string {
  if (!Number.isInteger(n) || n < 0) {
    throw new Error('Число должно быть целым и не меньше нуля');
  }
  if (n === 0) return 'ноль';

  const words: string[] = [];
  let remainder = n;

  for (const scale of SCALES) {
    const count = Math.floor(remainder / scale.threshold);
    remainder %= scale.threshold;
    if (count) {
      words.push(...groupToWords(count, scale.gender));
      words.push(pluralForm(count, scale.one, scale.few, scale.many));
    }
  }

  if (remainder || words.length === 0) {
    words.push(...groupToWords(remainder, gender));
  }

  return words.join(' ');
}

/** Слово, стоящее после числа, в трёх формах: «документ» / «документа» / «документов». */
export interface CountedWordForms {
  one: string;
  few: string;
  many: string;
}

/**
 * Число прописью вместе с согласованным словом: `countWords(21, {...})`
 * → «двадцать один документ», `countWords(22, {...})` → «двадцать два
 * документа», `countWords(25, {...})` → «двадцать пять документов».
 *
 * Отдельная функция, а не то, что вызывающий код собирает сам: между
 * согласованием числительного (`один документ`, а не `одна документ`)
 * и согласованием следующего за ним слова (`документ`/`документа`/
 * `документов`) достаточно легко перепутать род в одном месте и забыть
 * про 11–14 в другом.
 */
export function countWords(
  n: number,
  forms: CountedWordForms,
  gender: NumberGender = 'male',
): string {
  return `${numberInWords(n, gender)} ${pluralForm(n, forms.one, forms.few, forms.many)}`;
}
