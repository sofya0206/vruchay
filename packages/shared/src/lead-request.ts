/**
 * Удобное время звонка. Часовой пояс московский и назван в форме прямо:
 * «после обеда» без пояса — это назначенный и пропущенный звонок.
 */
export const CALL_TIMES = ['morning', 'day', 'evening', 'mail'] as const;
export type CallTime = (typeof CALL_TIMES)[number];

export const CALL_TIME_LABELS: Record<CallTime, string> = {
  morning: 'Утром, с 9 до 12 по Москве',
  day: 'Днём, с 12 до 15 по Москве',
  evening: 'После 15 по Москве',
  mail: 'Не звоните, напишите на почту',
};

/**
 * Текст согласия и его редакция.
 *
 * Доказывать наличие согласия обязан оператор, и «галочка же стояла» без
 * записи о том, на что человек соглашался, не работает: текст со временем
 * меняется. Редакцию сервер кладёт в заявку в момент приёма.
 */
export const CONSENT_TEXT_VERSION = '2026-08-29';
export const CONSENT_TEXT =
  'Согласен на обработку моих персональных данных для ответа на заявку.';

/**
 * Тело заявки, каким его шлёт форма.
 *
 * Описано здесь, чтобы форма и схема на сервере не разъезжались молча:
 * форма собирает объект этого типа, сервер проверяет, что его схема такой
 * объект принимает. Переименуйте поле в одном месте — сборка встанет
 * в обоих, а не заявка потеряется в проде.
 */
export interface LeadRequest {
  orgName: string;
  contact: string;
  email: string;
  phone?: string;
  volume?: VolumeBand;
  eventKinds?: EventKind[];
  callTime?: CallTime;
  comment?: string;
  /** Согласие на обработку данных: без него заявку не принимают. */
  consent: true;
  /** Поле-ловушка: у человека пустое, автомат его заполняет. */
  website?: string;
}
