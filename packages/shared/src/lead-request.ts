/**
 * Справочники формы «Обсудить условия».
 *
 * Публичных цен у сервиса нет: объём и стоимость обсуждаются в разговоре.
 * Поэтому единственный вход для организации — заявка, и её поля должны
 * одинаково пониматься кабинетом, посадочной страницей и сервером.
 *
 * Списки лежат здесь, а не по копии в каждом приложении, потому что сервер
 * принимает их по белому списку. Разойдись значения — форма начала бы
 * получать отказ на правильном ответе, и заметили бы мы это не по ошибке
 * в журнале, а по пропавшим заявкам.
 */

/** Объём документов в год. Диапазоны, а не число: точного никто не знает. */
