/**
 * Правила награждения по местам — заглушка.
 *
 * TODO(9.5): правил награждения в проекте пока нет ни в каком виде.
 * Колонка «place» заводится импортом (apps/server/src/import/column-names.ts),
 * но что с ней делать — не решено и нигде не реализовано; в юнит-экономике
 * (docs/business/unit-economics.md) правила награждения по местам значатся
 * фичей тарифа «Максимум», то есть работа ещё впереди.
 *
 * Когда правила появятся, проверка списка должна будет отвечать на вопросы
 * вроде «первое место занято дважды», «за третье место выдаётся диплом,
 * а в документе грамота», «в возрастной группе призёров больше, чем мест».
 * Ради этого здесь описан интерфейс: остальная проверка от него не зависит
 * и работает без него, а когда правила будут готовы — их подключат сюда,
 * не трогая ничего вокруг.
 *
 * До тех пор checkAwardingRules всегда возвращает пустой список, и в отчёт
 * попадает оговорка о том, что места не проверялись.
 */

import type { RowProblem } from './problems';

/** Одна строка списка глазами правил награждения. */
export interface AwardingRow {
  rowId: string;
  /** Значения колонок получателя: place, category, result и остальные. */
  data: Record<string, string>;
}

/** Настройки награждения документа. Состав определится вместе с 9.5. */
export interface AwardingRules {
  /** Колонка с занятым местом. */
  placeColumn?: string;
  /** Колонка, разделяющая участников на независимые зачёты. */
  groupColumn?: string;
}

export interface AwardingCheck {
  rowId: string;
  problems: RowProblem[];
}

/**
 * Пока правил нет — проверять нечего.
 *
 * Возвращает пустой список, а не бросает исключение: проверка списка
 * не должна вставать из-за незаконченной соседней задачи.
 */
export function checkAwardingRules(
  _rows: AwardingRow[],
  _rules: AwardingRules | null,
): AwardingCheck[] {
  return [];
}

/** Готовы ли правила награждения. Пока нет — отчёт скажет об этом вслух. */
export const AWARDING_RULES_READY = false;

export const AWARDING_RULES_CAVEAT =
  'Места и правила награждения не проверялись — этой части сервиса ещё нет';
