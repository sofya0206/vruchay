/**
 * Правила награждения глазами проверки списка — заглушка.
 *
 * Сами правила в сервисе есть и работают: набор собирается на вкладке
 * «Правила» (модель AwardRuleSet, apps/server/src/awards), привязывается
 * к материалу и раскладывает протокол по документам. Чего нет — так это
 * их разбора здесь: проверка списка не отвечает на вопросы вроде «первое
 * место занято дважды», «за третье место выдаётся диплом, а в документе
 * грамота», «в возрастной группе призёров больше, чем мест».
 *
 * Ради этого здесь описан интерфейс: остальная проверка от него не зависит
 * и работает без него, а когда разбор напишут — его подключат сюда,
 * не трогая ничего вокруг.
 *
 * До тех пор checkAwardingRules всегда возвращает пустой список, и в отчёт
 * попадает оговорка о том, что места проверка не смотрела.
 */

import type { RowProblem } from './problems';

/** Одна строка списка глазами правил награждения. */
export interface AwardingRow {
  rowId: string;
  /** Значения колонок получателя: place, category, result и остальные. */
  data: Record<string, string>;
}

/** Настройки награждения документа. Состав определится вместе с 9.5. */
export interface AwardingRules {
  /** Колонка с занятым местом. */
  placeColumn?: string;
  /** Колонка, разделяющая участников на независимые зачёты. */
  groupColumn?: string;
}

export interface AwardingCheck {
  rowId: string;
  problems: RowProblem[];
}

/**
 * Пока правил нет — проверять нечего.
 *
 * Возвращает пустой список, а не бросает исключение: проверка списка
 * не должна вставать из-за незаконченной соседней задачи.
 */
export function checkAwardingRules(
  _rows: AwardingRow[],
  _rules: AwardingRules | null,
): AwardingCheck[] {
  return [];
}

/**
 * Разбирает ли проверка списка правила награждения. Пока нет — отчёт
 * скажет об этом вслух, чтобы на её молчание не полагались.
 */
export const AWARDING_RULES_READY = false;

/*
 * Прежний текст — «этой части сервиса ещё нет» — врал: вкладка «Правила»
 * работает и набор правил собирает. Не хватает не функции, а её разбора
 * в проверке списка, и говорить надо именно об этом.
 */
export const AWARDING_RULES_CAVEAT =
  'Занятые места и правила награждения проверка не смотрела: набор правил ' +
  'на вкладке «Правила» она не разбирает';
