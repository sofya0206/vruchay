import { describe, expect, it } from 'vitest';
import { NBSP, NNBSP, typographRu } from './typography';

describe('русская типографика подставленных значений', () => {
  it('ставит ёлочки вместо машинописных кавычек', () => {
    expect(typographRu('АО "Звёздочка"')).toBe('АО «Звёздочка»');
  });

  it('вложенные кавычки делает лапками', () => {
    expect(typographRu('ООО "Школа "Радуга""')).toBe('ООО «Школа „Радуга“»');
  });

  it('не трогает дефис внутри слова', () => {
    expect(typographRu('спортивно-массовый')).toBe('спортивно-массовый');
  });

  it('отбитый пробелами дефис делает тире', () => {
    expect(typographRu('Иванов - победитель')).toBe(`Иванов${NBSP}— победитель`);
  });

  it('в диапазоне чисел ставит среднее тире', () => {
    expect(typographRu('17-19 июня 2026')).toBe('17–19 июня 2026');
  });

  it('склеивает инициалы между собой и с фамилией', () => {
    expect(typographRu('И.И.Иванов')).toBe(`И.${NNBSP}И.${NNBSP}Иванов`);
    expect(typographRu('И. И. Иванов')).toBe(`И.${NNBSP}И.${NNBSP}Иванов`);
  });

  it('не отрывает город от сокращения и чинит слипшееся', () => {
    expect(typographRu('г.Челябинск')).toBe(`г.${NBSP}Челябинск`);
    expect(typographRu('г. Челябинск')).toBe(`г.${NBSP}Челябинск`);
  });

  it('не отрывает единицы от числа', () => {
    expect(typographRu('120 руб.')).toBe(`120${NBSP}руб.`);
    expect(typographRu('100%')).toBe(`100${NBSP}%`);
    expect(typographRu('№ 5')).toBe(`№${NBSP}5`);
  });

  it('не оставляет одинокий предлог в конце строки', () => {
    expect(typographRu('победа в конкурсе')).toBe(`победа в${NBSP}конкурсе`);
    expect(typographRu('Иванов и Петров')).toBe(`Иванов и${NBSP}Петров`);
  });

  /*
   * Значение прогоняется через типографику дважды: один раз при измерении
   * («влезет ли»), второй — при печати. Если второй прогон меняет текст,
   * измеренное и напечатанное расходятся, и вердикт «влезает» перестаёт
   * что-либо значить.
   */
  it('повторный прогон ничего не меняет', () => {
    const samples = [
      'АО "Звёздочка" - лауреат',
      'И.И.Иванов, г.Челябинск',
      '17-19 июня 2026 года, 100% участников',
      'ООО "Школа "Радуга"" и её ученики',
      'победа в конкурсе № 5 на 120 руб.',
    ];
    for (const sample of samples) {
      const once = typographRu(sample);
      expect(typographRu(once), sample).toBe(once);
    }
  });

  it('правила выключаются по отдельности', () => {
    expect(typographRu('АО "Звёздочка"', { quotes: false })).toBe('АО "Звёздочка"');
    expect(typographRu('победа в конкурсе', { nbsp: false })).toBe('победа в конкурсе');
  });
});
