import { describe, expect, it } from 'vitest';
import {
  fullNameOf,
  hasPairedForms,
  resolvePairedForms,
  rowGender,
  substituteForRow,
} from './paired-forms';

/*
 * Парные формы печатаются на бумаге и вручаются при всех. Искажённое
 * слово — «награждёна», «прошёлла» — заметит не разработчик, а человек
 * на сцене, и заметит на трёхстах экземплярах сразу.
 */

const male = (text: string) => resolvePairedForms(text, 'male');
const female = (text: string) => resolvePairedForms(text, 'female');
const unknown = (text: string) => resolvePairedForms(text, 'unknown');

describe('чередования — то, на чём ломается простая склейка', () => {
  it('«награждён(а)» → «награждена», а не «награждёна»', () => {
    expect(female('награждён(а)')).toBe('награждена');
    expect(male('награждён(а)')).toBe('награждён');
  });

  it('«прошёл(ла)» → «прошла», а не «прошёлла»', () => {
    expect(female('прошёл(ла) обучение')).toBe('прошла обучение');
    expect(male('прошёл(ла) обучение')).toBe('прошёл обучение');
  });

  it('«занял(а)» → «заняла»', () => {
    expect(female('занял(а) первое место')).toBe('заняла первое место');
    expect(male('занял(а) первое место')).toBe('занял первое место');
  });

  it('«победитель(ница)» → «победительница»', () => {
    expect(female('победитель(ница)')).toBe('победительница');
    expect(male('победитель(ница)')).toBe('победитель');
  });

  it('«стал(а)» → «стала»', () => {
    expect(female('стал(а) призёром')).toBe('стала призёром');
    expect(male('стал(а) призёром')).toBe('стал призёром');
  });

  it('«отмечен(а)» → «отмечена»', () => {
    expect(female('отмечен(а) дипломом')).toBe('отмечена дипломом');
    expect(male('отмечен(а) дипломом')).toBe('отмечен дипломом');
  });

  it('чередование на «ён» работает и на других глаголах', () => {
    expect(female('приглашён(а)')).toBe('приглашена');
    expect(female('включён(а) в состав')).toBe('включена в состав');
  });

  it('чередование на «ёл» работает и на других глаголах', () => {
    expect(female('нашёл(ла)')).toBe('нашла');
    expect(female('вошёл(ла) в число финалистов')).toBe('вошла в число финалистов');
  });

  it('заглавная буква основы сохраняется', () => {
    // «Награждается» — первое слово фразы, и оно с большой буквы.
    expect(female('Награждён(а) за первое место')).toBe('Награждена за первое место');
    expect(female('Прошёл(ла) обучение')).toBe('Прошла обучение');
  });

  it('дефис в «победитель(-ница)» — подсказка, а не часть слова', () => {
    expect(female('победитель(-ница)')).toBe('победительница');
    expect(male('победитель(-ница)')).toBe('победитель');
  });
});

describe('пол не определён — печатаем как написано', () => {
  it('скобочная форма остаётся нетронутой', () => {
    // «Награждён(а)» — законная запись на бумаге, а не поломка:
    // останавливать из-за неё выпуск не за что.
    expect(unknown('Награждён(а) за первое место')).toBe('Награждён(а) за первое место');
  });

  it('форма с чертой печатается через косую', () => {
    expect(unknown('награждён|награждена')).toBe('награждён/награждена');
    expect(unknown('он|она')).toBe('он/она');
  });
});

describe('явная пара через черту — запасной ход организатора', () => {
  it('выбирает нужную половину', () => {
    expect(male('награждён|награждена')).toBe('награждён');
    expect(female('награждён|награждена')).toBe('награждена');
  });

  it('чинит то, что таблица чередований взяла бы неверно', () => {
    // Ради этого запасной ход и нужен: не дожидаясь релиза.
    expect(female('мастер|мастерица спорта')).toBe('мастерица спорта');
  });

  it('работает на словах с дефисом', () => {
    expect(female('генерал-майор|генерал-майорша')).toBe('генерал-майорша');
  });
});

describe('обычные скобки в тексте — не трогать', () => {
  /*
   * Правило узкое намеренно. Всё, что ниже, встречается в настоящих
   * грамотах, и переосмысление любой из этих скобок как парной формы —
   * испорченный документ.
   */
  it('пробел перед скобкой отменяет правило', () => {
    expect(female('баттерфляй (50 м)')).toBe('баттерфляй (50 м)');
    expect(female('Иванов (тренер)')).toBe('Иванов (тренер)');
  });

  it('пробел внутри скобки отменяет правило', () => {
    expect(female('далее(далее — Участник)')).toBe('далее(далее — Участник)');
  });

  it('цифры и латиница внутри скобки отменяют правило', () => {
    expect(female('дистанция(50м)')).toBe('дистанция(50м)');
    expect(female('стиль(free)')).toBe('стиль(free)');
  });

  it('заглавная буква внутри скобки отменяет правило', () => {
    expect(female('общество(ДЮСШ)')).toBe('общество(ДЮСШ)');
  });

  it('слишком длинное содержимое скобки отменяет правило', () => {
    expect(female('плавание(вольныйстиль)')).toBe('плавание(вольныйстиль)');
  });

  it('односимвольная основа отменяет правило', () => {
    expect(female('т(ая)')).toBe('т(ая)');
  });
});

describe('источник пола', () => {
  it('явная колонка сильнее догадки по ФИО', () => {
    // Тот же принцип, что и у переменных: колонка организации сильнее
    // нашей догадки. Здесь это ещё и единственный способ напечатать
    // верно там, где ФИО пола не выдаёт.
    expect(rowGender({ name: 'Иванов Пётр', pol: 'ж' })).toBe('female');
    expect(rowGender({ name: 'Петрова Мария', gender: 'м' })).toBe('male');
  });

  it('колонку узнаёт и по-русски, и по-латински', () => {
    expect(rowGender({ пол: 'ж' })).toBe('female');
    expect(rowGender({ pol: 'ж' })).toBe('female');
    expect(rowGender({ gender: 'female' })).toBe('female');
    expect(rowGender({ sex: 'f' })).toBe('female');
  });

  it('понимает ходовые написания значений', () => {
    for (const value of ['м', 'М', 'муж', 'Муж.', 'мужской', 'male', 'M']) {
      expect(rowGender({ [`пол`]: value })).toBe('male');
    }
    for (const value of ['ж', 'Ж', 'жен', 'Жен.', 'женский', 'female', 'F']) {
      expect(rowGender({ [`пол`]: value })).toBe('female');
    }
  });

  it('без колонки определяет пол по ФИО', () => {
    expect(rowGender({ name: 'Иванов Пётр Ильич' })).toBe('male');
    expect(rowGender({ name: 'Петрова Мария Ивановна' })).toBe('female');
  });

  it('пустая или мусорная колонка не мешает разобрать ФИО', () => {
    // «мужик» — не указание, а мусор. Угадать верно лучше,
    // чем напечатать «награждён(а)».
    expect(rowGender({ name: 'Петрова Мария', пол: '' })).toBe('female');
    expect(rowGender({ name: 'Иванов Пётр', пол: 'мужик' })).toBe('male');
  });

  it('когда не отвечает ни колонка, ни ФИО — «unknown»', () => {
    expect(rowGender({})).toBe('unknown');
    expect(rowGender({ name: 'John Smith' })).toBe('unknown');
    expect(rowGender({ name: 'Женя Саша' })).toBe('unknown');
  });
});

describe('порядок: парные формы разбираются до подстановки колонок', () => {
  /*
   * Иначе данные получателя будут переосмыслены как парная форма.
   * Текст макета пишет организатор и отвечает за него; чужой файл
   * со списком участников трогать нельзя.
   */
  it('скобки в данных получателя остаются нетронутыми', () => {
    const text = 'Награждён(а) в дисциплине %sport';
    expect(substituteForRow(text, { name: 'Петрова Мария', sport: 'баттерфляй(50м)' })).toBe(
      'Награждена в дисциплине баттерфляй(50м)',
    );
  });

  it('черта в данных получателя не считается парной формой', () => {
    const text = 'Награждён(а), команда %team';
    expect(substituteForRow(text, { name: 'Иванов Пётр', team: 'Заря|Восток' })).toBe(
      'Награждён, команда Заря|Восток',
    );
  });

  it('парная форма, похожая на настоящую, в данных не срабатывает', () => {
    // Самый опасный случай: значение колонки выглядит ровно как то,
    // что мы обязаны раскрыть в макете.
    const text = '%note';
    expect(substituteForRow(text, { name: 'Петрова Мария', note: 'награждён(а)' })).toBe(
      'награждён(а)',
    );
  });

  it('пол берётся из той же строки, что и подставляемые данные', () => {
    const text = 'Награждён(а) %name_dat';
    expect(substituteForRow(text, { name: 'Петрова Мария', name_dat: 'Петровой Марии' })).toBe(
      'Награждена Петровой Марии',
    );
  });
});

describe('поиск парных форм для проверки перед выпуском', () => {
  it('находит скобочную форму', () => {
    expect(hasPairedForms('Награждён(а) за первое место')).toBe(true);
  });

  it('находит форму с чертой', () => {
    expect(hasPairedForms('награждён|награждена')).toBe(true);
  });

  it('не считает парной формой обычные скобки', () => {
    expect(hasPairedForms('баттерфляй (50 м)')).toBe(false);
    expect(hasPairedForms('Награждается %name_dat')).toBe(false);
  });

  it('ответ не зависит от прошлых вызовов', () => {
    // Глобальная регулярка с `test` таскала бы за собой lastIndex,
    // и второй одинаковый вопрос получал бы другой ответ.
    const text = 'Награждён(а) за первое место';
    expect(hasPairedForms(text)).toBe(true);
    expect(hasPairedForms(text)).toBe(true);
    expect(hasPairedForms(text)).toBe(true);
  });
});

describe('классы слов сверх двух чередований', () => {
  it('причастия и прилагательные: -ий/-ый → -ая', () => {
    // Простая склейка дала бы «занявшийая» и «награждённыйая».
    expect(female('занявший(ая)')).toBe('занявшая');
    expect(female('награждённый(ая)')).toBe('награждённая');
    expect(female('победивший(ая)')).toBe('победившая');
    expect(male('занявший(ая)')).toBe('занявший');
  });

  it('существительные на -ик: → -ица', () => {
    // Простая склейка дала бы «участникца» и «школьникца».
    expect(female('участник(ца)')).toBe('участница');
    expect(female('школьник(ца)')).toBe('школьница');
    expect(female('выпускник(ца)')).toBe('выпускница');
    expect(male('участник(ца)')).toBe('участник');
  });

  it('дефис не меняет разбор — заменяются те же буквы', () => {
    // Комментарий обещает замену окончания, и класс её и делает:
    // «участник(-ца)» не должно давать «участникца».
    expect(female('участник(-ца)')).toBe('участница');
    expect(female('победитель(-ница)')).toBe('победительница');
    expect(female('занявший(-ая)')).toBe('занявшая');
  });
});

describe('незнакомый класс — оставляем как написано', () => {
  /*
   * Дыра видна намеренно. Таблица классов заведомо неполна, и склеивать
   * вслепую нельзя: «студенткa» на трёхстах грамотах хуже, чем неудобная,
   * но читаемая запись «студент(ка)». Когда класс понадобится — он
   * добавляется сюда вместе с тестом, а до тех пор у организатора есть
   * запасной ход через черту.
   */
  it('окончание -ка не распознаётся и текст не трогается', () => {
    expect(female('студент(ка)')).toBe('студент(ка)');
    expect(female('спортсмен(ка)')).toBe('спортсмен(ка)');
  });

  it('окончание -ица после согласной не распознаётся', () => {
    expect(female('мастер(ица)')).toBe('мастер(ица)');
  });

  it('мужской род тоже не трогает нераспознанное', () => {
    // Отбросить скобку у мужчины само по себе безопасно, но в записи,
    // которую мы не опознали как парную форму, это потеря текста.
    expect(male('студент(ка)')).toBe('студент(ка)');
    expect(unknown('студент(ка)')).toBe('студент(ка)');
  });

  it('основа с «ё» без подходящего чередования не склеивается', () => {
    // «прошёл(а)» не должно давать «прошёла».
    expect(female('прошёл(а)')).toBe('прошёл(а)');
    expect(female('награждён(ая)')).toBe('награждён(ая)');
  });

  it('запасной ход через черту чинит любой такой случай', () => {
    expect(female('студент|студентка')).toBe('студентка');
    expect(female('мастер|мастерица')).toBe('мастерица');
  });

  it('нераспознанное не считается парной формой при проверке', () => {
    // Иначе 9.3 предупреждала бы о том, чего мы не трогаем.
    expect(hasPairedForms('студент(ка)')).toBe(false);
    expect(hasPairedForms('участник(ца)')).toBe(true);
  });
});

describe('запись капсом', () => {
  /*
   * «НАГРАЖДЁН(А)» в шапке грамоты — обычное дело, и женщине это должно
   * печататься как «НАГРАЖДЕНА», а не как есть.
   */
  it('чередование работает и сохраняет регистр', () => {
    expect(female('НАГРАЖДЁН(А)')).toBe('НАГРАЖДЕНА');
    expect(male('НАГРАЖДЁН(А)')).toBe('НАГРАЖДЁН');
  });

  it('прочие классы капсом', () => {
    expect(female('ПРОШЁЛ(ЛА)')).toBe('ПРОШЛА');
    expect(female('ЗАНЯЛ(А)')).toBe('ЗАНЯЛА');
    expect(female('УЧАСТНИК(ЦА)')).toBe('УЧАСТНИЦА');
    expect(female('ЗАНЯВШИЙ(АЯ)')).toBe('ЗАНЯВШАЯ');
  });

  it('заглавные в скобке при строчной основе — аббревиатура, не форма', () => {
    // Ради этого регистры и должны согласовываться: иначе «общество(ДЮСШ)»
    // стало бы парной формой и потеряло бы содержимое скобок.
    expect(female('общество(ДЮСШ)')).toBe('общество(ДЮСШ)');
    expect(male('общество(ДЮСШ)')).toBe('общество(ДЮСШ)');
    expect(hasPairedForms('общество(ДЮСШ)')).toBe(false);
  });

  it('капс, не подошедший ни под один класс, тоже не трогается', () => {
    expect(male('ОБЩЕСТВО(ДЮСШ)')).toBe('ОБЩЕСТВО(ДЮСШ)');
    expect(female('ОБЩЕСТВО(ДЮСШ)')).toBe('ОБЩЕСТВО(ДЮСШ)');
  });
});

describe('ФИО, разложенное импортом по колонкам', () => {
  /*
   * `column-names.ts` умеет раскладывать шапку на «Фамилия», «Имя»,
   * «Отчество», и тогда колонки «name» просто нет. Отчество — самый
   * надёжный признак пола, и терять его из-за формы таблицы нельзя.
   */
  it('собирает ФИО из surname/firstname/patronymic', () => {
    expect(fullNameOf({ surname: 'Петрова', firstname: 'Мария', patronymic: 'Ивановна' })).toBe(
      'Петрова Мария Ивановна',
    );
  });

  it('колонка «name» сильнее разложенных', () => {
    expect(fullNameOf({ name: 'Иванов Пётр', surname: 'Петрова' })).toBe('Иванов Пётр');
  });

  it('пропущенные части не оставляют лишних пробелов', () => {
    expect(fullNameOf({ surname: 'Петрова', patronymic: 'Ивановна' })).toBe('Петрова Ивановна');
    expect(fullNameOf({})).toBe('');
  });

  it('пол определяется по отчеству из отдельной колонки', () => {
    expect(rowGender({ surname: 'Смирнов', firstname: 'Женя', patronymic: 'Петровна' })).toBe(
      'female',
    );
    expect(rowGender({ surname: 'Смирнов', firstname: 'Женя', patronymic: 'Петрович' })).toBe(
      'male',
    );
  });

  it('парная форма печатается верно на разложенных колонках', () => {
    const text = 'Награждён(а) %surname';
    expect(
      substituteForRow(text, { surname: 'Петрова', firstname: 'Мария', patronymic: 'Ивановна' }),
    ).toBe('Награждена Петрова');
  });
});
