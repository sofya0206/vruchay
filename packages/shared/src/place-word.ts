/**
 * Место словом: «за ПЕРВОЕ место», а не «за 1 место».
 *
 * На настоящих дипломах место пишут словом — так оно читается как награда,
 * а не как строка таблицы. Протокол при этом всегда приходит с цифрой,
 * и переписывать триста строк руками никто не станет.
 */
const WORDS = [
  'первое',
  'второе',
  'третье',
  'четвёртое',
  'пятое',
  'шестое',
  'седьмое',
  'восьмое',
  'девятое',
  'десятое',
];

export function placeWord(place: string): string {
  const source = place.trim();
  if (!source) return '';

  // «1», «1 место», «1-е» — в протоколах пишут по-разному.
  const digits = source.match(/^\d+/);
  if (!digits) return source;

  const number = Number(digits[0]);
  return WORDS[number - 1] ?? source;
}
