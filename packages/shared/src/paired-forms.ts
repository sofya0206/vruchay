import { substituteVariables } from './schema/layout';

/**
 * Парные формы: «награждён(а)», «занял(а)», «участник(ца)».
 *
 * Наградные тексты написаны от лица того, кто вручает, и потому всегда
 * в роде получателя. Организатор с этим уже живёт: на бумажных бланках
 * пишут «награждён(а)» и обводят нужное ручкой. Мы обводим за него.
 *
 * Синтаксиса фильтров здесь нет намеренно — макет остаётся плоским
 * текстом с плоскими переменными, и `schemaVersion` от этой правки
 * не меняется. Организатор пишет ровно то, что писал бы на бланке,
 * и учить его нечему.
 *
 * Запасной ход — явная пара через черту: «награждён|награждена».
 * Он нужен не для красоты: если наша таблица классов не знает слова,
 * человек чинит текст сам, не дожидаясь релиза.
 */

/** Пол получателя. «unknown» — не ошибка, а законная третья возможность. */
export type Gender = 'male' | 'female' | 'unknown';

/**
 * Скобочная форма: слово, вплотную скобка, внутри 1–5 кириллических
 * букв с необязательным ведущим дефисом.
 *
 * Правило нарочно узкое. В тексте грамоты полно обычных скобок —
 * «баттерфляй (50 м)», «Иванов (тренер)», «(далее — Участник)», — и все
 * они мимо: там есть пробел перед скобкой, или пробел внутри, или цифра,
 * или слишком длинное содержимое. Расширять его нельзя: цена ошибки —
 * искажённое слово на трёхстах грамотах.
 */
const BRACKET_FORM = /([А-Яа-яЁё]{2,})\((-?[А-Яа-яЁё]{1,5})\)/g;

/** Явная пара через черту: «награждён|награждена», «он|она». */
const PIPE_FORM = /([А-Яа-яЁё]+(?:-[А-Яа-яЁё]+)?)\|([А-Яа-яЁё]+(?:-[А-Яа-яЁё]+)?)/g;

/** Согласные, после которых женское «а» просто приклеивается. */
const HARD_CONSONANT_END = /[бвгджзклмнпрстфхцчшщ]$/;

/** Строчная кириллица — по её отсутствию узнаём запись капсом. */
const HAS_LOWERCASE = /[а-яё]/;

/**
 * Колонки, которыми организация задаёт пол явно.
 *
 * И кириллические, и латинские: подбор имён при импорте переводит
 * «Пол» в «pol», но колонку могли завести и руками.
 */
const GENDER_COLUMNS = ['пол', 'pol', 'gender', 'sex'];

const MALE_VALUES = new Set(['м', 'муж', 'мужской', 'мужчина', 'm', 'male']);
const FEMALE_VALUES = new Set(['ж', 'жен', 'женский', 'женщина', 'f', 'female']);

/**
 * Женская форма слова — или `null`, если класс слова нам незнаком.
 *
 * Приклеить окончание к основе напрямую нельзя: «награждён» + «а» дало бы
 * «награждёна», «прошёл» + «ла» — «прошёлла», «участник» + «ца» —
 * «участникца», «занявший» + «ая» — «занявшийая». Поэтому здесь таблица
 * классов, а не склейка.
 *
 * Незнакомый класс — это `null`, и текст остаётся как написан. Склеивать
 * вслепую нельзя: неудобная запись «студент(ка)» на бумаге читается,
 * а несуществующее слово «студенткa» на трёхстах грамотах — нет. Таблица
 * заведомо неполна, и это её нормальное состояние: слова добавляются
 * по мере того, как они встречаются, а до тех пор у организатора есть
 * запасной ход через черту — «студент|студентка».
 */
function femaleForm(stem: string, rawEnding: string): string | null {
  // Дефис в «победитель(-ница)» и «участник(-ца)» — типографский вариант
  // той же записи. Сколько букв основы заменить, решает таблица классов
  // ниже, а не наличие дефиса.
  const ending = rawEnding.replace(/^-/, '');
  const s = stem.toLowerCase();
  const e = ending.toLowerCase();
  // Запись капсом: «НАГРАЖДЁН(А)» в шапке грамоты — обычное дело.
  const upper = !HAS_LOWERCASE.test(stem + ending);

  // награждён → награждена, приглашён → приглашена, включён → включена.
  if (e === 'а' && s.endsWith('ён')) return stem.slice(0, -2) + caseOf('ен', upper) + ending;
  // прошёл → прошла, нашёл → нашла, вошёл → вошла.
  if (e === 'ла' && s.endsWith('ёл')) return stem.slice(0, -2) + ending;

  // Основа с «ё» требует чередования, и раз ни одно не подошло — отступаем.
  // Иначе «прошёл(а)» уехало бы в общий случай и дало «прошёла».
  if (s.endsWith('ён') || s.endsWith('ёл')) return null;

  // занявший → занявшая, награждённый → награждённая.
  if (e === 'ая' && (s.endsWith('ий') || s.endsWith('ый'))) return stem.slice(0, -2) + ending;
  // участник → участница, школьник → школьница, выпускник → выпускница.
  if (e === 'ца' && s.endsWith('ик')) return stem.slice(0, -1) + ending;
  // победитель → победительница, слушатель → слушательница.
  if (e === 'ница' && s.endsWith('ь')) return stem + ending;
  // занял → заняла, отмечен → отмечена, стал → стала, он → она.
  if (e === 'а' && HARD_CONSONANT_END.test(s)) return stem + ending;

  return null;
}

function caseOf(text: string, upper: boolean): string {
  return upper ? text.toUpperCase() : text;
}

/**
 * Раскрывает парные формы в тексте макета.
 *
 * Вызывать до подстановки значений колонок, а не после. Иначе данные
 * получателя — «баттерфляй (50 м)», «Иванов (тренер)», название команды
 * с вертикальной чертой — попадут под эти правила и будут переосмыслены
 * как парная форма. Текст макета пишет организатор и отвечает за него;
 * данные получателей приходят из чужого файла, и трогать их нельзя.
 */
export function resolvePairedForms(text: string, gender: Gender): string {
  const withPipes = text.replace(PIPE_FORM, (_whole, male: string, female: string) => {
    if (gender === 'male') return male;
    if (gender === 'female') return female;
    // Пол не определён — печатаем обе формы через косую черту.
    // «Награждён/награждена» — законная запись на бумаге, а не поломка,
    // и выпуск из-за неё останавливать не за что.
    return `${male}/${female}`;
  });

  return withPipes.replace(BRACKET_FORM, (whole, stem: string, ending: string) => {
    // Регистр скобки должен согласоваться с основой. Заглавные внутри
    // при строчной основе — это аббревиатура, а не парная форма:
    // «общество(ДЮСШ)» трогать нельзя.
    if (!HAS_LOWERCASE.test(ending) && HAS_LOWERCASE.test(stem)) return whole;

    // Класс решает и за женскую форму, и за мужскую. Отбросить скобку
    // у мужчины само по себе безопасно, но делать это в записи, которую
    // мы не опознали как парную форму, — значит терять текст:
    // «ОБЩЕСТВО(ДЮСШ)» превратилось бы в «ОБЩЕСТВО».
    const female = femaleForm(stem, ending);
    if (female === null) return whole;

    if (gender === 'male') return stem;
    if (gender === 'female') return female;
    // Пол не определён — оставляем ровно как написано: «награждён(а)».
    return whole;
  });
}

/**
 * Есть ли в тексте парные формы.
 *
 * Отдаётся наружу для проверки списка перед выпуском (задача 9.3):
 * ей нужно сказать «в тексте есть парные формы, а у 12 строк пол
 * не определён». Саму проверку строк здесь не делаем — это её дело.
 *
 * Считаем через сам разбор, а не отдельной регуляркой: парная форма —
 * это ровно та запись, от которой результат зависит от пола. Иначе
 * проверка предупреждала бы о «студент(ка)», которую мы не трогаем,
 * и о «общество(ДЮСШ)», которая парной формой не является.
 */
export function hasPairedForms(text: string): boolean {
  return resolvePairedForms(text, 'male') !== resolvePairedForms(text, 'female');
}

/**
 * ФИО из строки таблицы.
 *
 * Импорт умеет раскладывать шапку на «surname», «firstname»,
 * «patronymic» (см. `column-names.ts`), и тогда колонки «name» просто
 * нет. Отчество — самый надёжный признак пола из всех, что у нас есть,
 * и терять его из-за формы таблицы нельзя.
 *
 * Порядок «Фамилия Имя Отчество» — тот, которого ждёт разбор в
 * `declension.ts` и в котором пишут протоколы.
 */
export function fullNameOf(data: Record<string, string>): string {
  const direct = (data.name ?? '').trim();
  if (direct) return direct;
  return [data.surname, data.firstname, data.patronymic]
    .map((part) => (part ?? '').trim())
    .filter(Boolean)
    .join(' ');
}

/**
 * Пол получателя по строке таблицы.
 *
 * Сначала явная колонка, и только потом догадка по ФИО — тот же
 * порядок, что уже принят для переменных: своя колонка организации
 * сильнее нашей догадки.
 */
export function rowGender(data: Record<string, string>): Gender {
  for (const [key, raw] of Object.entries(data)) {
    if (!GENDER_COLUMNS.includes(key.trim().toLowerCase())) continue;
    // «Муж.», «М .» — точки и пробелы в такой колонке ничего не значат.
    const value = (raw ?? '').toLowerCase().replace(/[.\s]/g, '');
    if (MALE_VALUES.has(value)) return 'male';
    if (FEMALE_VALUES.has(value)) return 'female';
    // Колонка есть, но значение нам незнакомо («мужик», «муж/жен»).
    // Это не указание, а мусор, — падаем дальше, к разбору ФИО:
    // угадать верно лучше, чем напечатать «награждён(а)».
  }

  const byName = detectGenderFromName(fullNameOf(data));
  return byName === 'androgynous' ? 'unknown' : byName;
}

/**
 * Текст для одной строки таблицы: сначала парные формы, потом переменные.
 *
 * Один вход для превью в редакторе, серверного рендера в Chromium и письма —
 * иначе организатор увидел бы на экране одно, на бумаге получил другое,
 * а в письме третье, и узнал бы об этом уже от участников.
 */
export function substituteForRow(
  text: string,
  data: Record<string, string>,
  onMissing?: (name: string) => string,
): string {
  return substituteVariables(resolvePairedForms(text, rowGender(data)), data, onMissing);
}
