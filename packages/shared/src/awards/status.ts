/**
 * Разбор статуса участника: финишировал, снят, не стартовал.
 *
 * Протокол не полагается на графу «место» там, где участника сняли:
 * у дисквалифицированного место либо пустое, либо стоит прочерк, либо —
 * что хуже всего — остаётся последним по времени. Правило «с 1 по 3 место»
 * такого участника не тронет, а правило «всем участникам» выдаст ему
 * грамоту, которой он по регламенту лишён. Поэтому статус разбирается
 * отдельно и проверяется раньше места.
 *
 * Как и с местом, в сомнении возвращаем null: движок сообщит
 * «статус не распознан», и решать будет человек.
 */

/**
 * Коды статусов.
 *
 * `withdrawn` («снят») отделён от `dsq`: снятие по решению судьи и снятие
 * за нарушение — разные вещи для регламента, и федерация может награждать
 * первого утешительной грамотой, а второго нет.
 */
export const AWARD_STATUSES = ['ok', 'dsq', 'dns', 'dnf', 'dnq', 'withdrawn'] as const;
export type AwardStatus = (typeof AWARD_STATUSES)[number];

/** Как называть статус в конструкторе правил и в отчёте. */
export const AWARD_STATUS_TITLES: Record<AwardStatus, string> = {
  ok: 'В зачёте',
  dsq: 'Дисквалифицирован (DSQ)',
  dns: 'Не стартовал (DNS)',
  dnf: 'Не финишировал (DNF)',
  dnq: 'Не прошёл квалификацию (DNQ)',
  withdrawn: 'Снят',
};

/** Статусы, при которых документ по общему правилу не полагается. */
export const NO_AWARD_STATUSES: AwardStatus[] = ['dsq', 'dns', 'dnf', 'dnq', 'withdrawn'];

/**
 * Словарь написаний. Проверяется по вхождению, поэтому **порядок важен**:
 * «снят с дистанции» и «дисквалифицирован» оба содержат корни из разных
 * строк, и более определённое написание должно стоять выше.
 */
const ALIASES: [RegExp, AwardStatus][] = [
  [/^(dsq|dq|дискв)/, 'dsq'],
  [/дисквал/, 'dsq'],
  [/^(dns)/, 'dns'],
  [/^(dnf)/, 'dnf'],
  [/^(dnq)/, 'dnq'],
  [/не\s*допущ/, 'dnq'],
  [/не\s*прош(е|ё)л/, 'dnq'],
  [/не\s*старт/, 'dns'],
  [/не\s*яв/, 'dns'],
  [/^(н\/?я|н\/?с)$/, 'dns'],
  [/неявка/, 'dns'],
  [/не\s*финиш/, 'dnf'],
  [/сош(е|ё)л|сошла|сход/, 'dnf'],
  [/^(н\/?ф)$/, 'dnf'],
  [/сня(т|та|л)/, 'withdrawn'],
  [/отказ/, 'withdrawn'],
  [/^(wd|dsqp)/, 'withdrawn'],
  /*
   * Положительная отметка сверяется целиком, а не по началу строки.
   * По началу «зачёт аннулирован» совпадал с «зачет» и означал допуск —
   * то есть спортсмен, у которого результат отменён, получал грамоту.
   * Всё, что длиннее известного слова, честнее считать непонятным:
   * непонятное останавливает выдачу, а ложный допуск — печатает документ.
   */
  [/^(ok|fin|финиш|финишировал|финишировала|зачет|в\s*зачете|есть|да|допущен|допущена)$/, 'ok'],
];

/** Пустая графа и прочерк значат «участвовал как обычно». */
const EMPTY = /^([-–—‒]+|\+)?$/;

/**
 * Разбирает графу статуса. Пусто или прочерк — 'ok': отсутствие отметки
 * в протоколе означает, что с участником всё в порядке. null — написано
 * что-то нераспознанное; такую строку нельзя молча считать зачётной.
 */
export function parseStatus(raw: string | null | undefined): AwardStatus | null {
  const value = String(raw ?? '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/\u00a0/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/[.,;:]+$/g, '')
    .trim();

  if (EMPTY.test(value)) return 'ok';

  for (const [pattern, status] of ALIASES) {
    if (pattern.test(value)) return status;
  }
  return null;
}
